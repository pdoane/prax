// Bytes of xorshift32 from a seed of one.
String noise(size_t size) {
    String out;
    uint32_t x = 1;
    for (size_t i = 0; i < size; ++i) {
        x ^= x << 13;
        x ^= x >> 17;
        x ^= x << 5;
        out.append(char(x & 0xff));
    }
    return out;
}

