// Bytes of xorshift32 from a seed of one.
String noise(size_t size) {
    Array<char> bytes(size);
    uint32_t x = 1;
    for (size_t i = 0; i < size; ++i) {
        x ^= x << 13;
        x ^= x >> 17;
        x ^= x << 5;
        bytes.data()[i] = char(uint8_t(x));
    }
    return String(PrStringView{bytes.data(), size});
}

