struct Decoded {
    Outcome result;
    size_t consumed;
    String text;
};

// Decodes `input` in pieces of `inputChunk` bytes into an output of `outputChunk` bytes, with a decoder that takes
// windows up to `windowLimit`.
Decoded decode(PrByteView input, size_t inputChunk, size_t outputChunk, int64_t windowLimit = kPrZstdDefaultWindowLimit) {
    PrZstdDecoder* d = prZstdDecoderCreate(size_t(windowLimit));
    Decoded decoded{Outcome_Input, 0, String()};
    Array<uint8_t> output;
    output.resize(uint32_t(outputChunk));
    size_t at = 0;
    for (;;) {
        size_t size = inputChunk < input.size - at ? inputChunk : input.size - at;
        size_t consumed = 0;
        size_t written = 0;
        Outcome result = readOutcome(d, PrByteView{input.data + at, size}, at + size == input.size, &consumed,
            output.data(), outputChunk, &written);
        // Checked in place, since a check that doctest records on every read costs more than the read.
        if (consumed > size || written > outputChunk)
            FAIL("a read consumed or wrote past what it was given");
        decoded.text.append(chars(output.data(), written));
        at += consumed;
        decoded.result = result;
        if (result != Outcome_Input && result != Outcome_Output)
            break;
        // A read makes progress.
        if (consumed == 0 && written == 0 && result != Outcome_Input)
            FAIL("a read made no progress");
    }
    decoded.consumed = at;
    prZstdDecoderDestroy(d);
    return decoded;
}

// Decodes the whole of `stream` into an output of `capacity` bytes with one read.
Decoded decodeInto(PrByteView stream, size_t capacity) {
    PrZstdDecoder* d = prZstdDecoderCreate(kPrZstdDefaultWindowLimit);
    Array<uint8_t> output;
    output.resize(uint32_t(capacity));
    Decoded decoded{Outcome_Input, 0, String()};
    size_t written = 0;
    decoded.result = readOutcome(d, stream, true, &decoded.consumed, capacity != 0 ? output.data() : nullptr, capacity, &written);
    REQUIRE(written <= capacity);
    decoded.text.append(chars(output.data(), written));
    prZstdDecoderDestroy(d);
    return decoded;
}

// How the whole of `stream` decodes, however large its content.
Outcome resultOf(PrByteView stream) {
    return decode(stream, stream.size + 1, 1 << 16).result;
}

