// Tables of the EAC block that best represents one channel of an ETC1S block. The transcoders of ETC1S to the alpha
// block of ETC2 and to EAC R11 read them. Each table is indexed by the ETC1 modifier table, the channel's base value of
// five bits, and the run of selectors that the block's texels use, in the order of kBasisEacRuns.
