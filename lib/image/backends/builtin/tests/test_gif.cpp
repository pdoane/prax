// Returns the bytes of one vector with the byte at `at` set to `value`.
Array<uint8_t> patched(const Vector& vector, uint32_t at, uint8_t value) {
    Array<uint8_t> bytes;
    bytes.append(vector.bytes);
    bytes[at] = value;
    return bytes;
}

// Returns the bytes with the loop count in their Netscape application extension set to `loops`.
Array<uint8_t> withLoops(Span<const uint8_t> bytes, uint16_t loops) {
    const PrStringView text(reinterpret_cast<const char*>(bytes.data()), bytes.count());
    const uint32_t at = uint32_t(prStringFind(text, "NETSCAPE2.0"));
    REQUIRE(at != text.size);
    Array<uint8_t> out;
    out.append(bytes);
    out[at + 13] = uint8_t(loops & 0xFF);
    out[at + 14] = uint8_t(loops >> 8);
    return out;
}

// Decodes one frame through an open animation and returns the resulting screen.
Array<uint8_t> frameOf(Animation* animation, const Vector& vector, uint32_t frame) {
    Array<uint8_t> pixels(size_t(vector.width) * vector.height * 4);
    prMemFill(pixels.data(), 0xCD, pixels.count());
    REQUIRE(animationFrame(animation, frame, pixels.data(), pixels.count()));
    return pixels;
}

const Vector& named(const char* name) {
    for (const Vector& vector : vectors()) {
        if (PrStringView(vector.name) == name) {
            return vector;
        }
    }
    FAIL("no vector named ", name);
    return vectors()[0];
}

