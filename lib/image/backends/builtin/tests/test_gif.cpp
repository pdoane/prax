// Returns the bytes of one vector with the byte at `at` set to `value`.
std::vector<uint8_t> patched(const Vector& vector, size_t at, uint8_t value) {
    std::vector<uint8_t> bytes = vector.bytes;
    bytes[at] = value;
    return bytes;
}

// Returns the bytes with the loop count in their Netscape application extension set to `loops`.
std::vector<uint8_t> withLoops(const std::vector<uint8_t>& bytes, uint16_t loops) {
    const std::string text(reinterpret_cast<const char*>(bytes.data()), bytes.size());
    const size_t at = text.find("NETSCAPE2.0");
    REQUIRE(at != std::string::npos);
    std::vector<uint8_t> out = bytes;
    out[at + 13] = uint8_t(loops & 0xFF);
    out[at + 14] = uint8_t(loops >> 8);
    return out;
}

// Decodes one frame through an open animation and returns the resulting screen.
std::vector<uint8_t> frameOf(Animation* animation, const Vector& vector, uint32_t frame) {
    std::vector<uint8_t> pixels(size_t(vector.width) * vector.height * 4, 0xCD);
    REQUIRE(animationFrame(animation, frame, pixels.data(), pixels.size()));
    return pixels;
}

const Vector& named(const char* name) {
    for (const Vector& vector : vectors()) {
        if (std::string(vector.name) == name) {
            return vector;
        }
    }
    FAIL("no vector named ", name);
    return vectors()[0];
}

