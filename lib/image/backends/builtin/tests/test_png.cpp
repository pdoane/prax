    decodeOnly.encodeBoundFn = nullptr;
    decodeOnly.encodeFn = nullptr;
    PrImageCodec* codec = prImageBuiltinCreate(&decodeOnly);
    Array<uint8_t> pixels(64 * 600 * 4);
    prMemFill(pixels.data(), 0x11, pixels.count());
    const PrPixelView view{pixels.data(), size_t(64) * 4, {64, 600}};
    size_t size = 0;
    REQUIRE(prImageCodecEncode(codec, "image/png", view, nullptr, 0, &size) == PrStatus_Ok);
    Array<uint8_t> encoded(size);
    REQUIRE(prImageCodecEncode(codec, "image/png", view, encoded.data(), encoded.count(), &size) == PrStatus_Ok);
    prImageCodecDestroy(codec);
    // The zlib stream starts after the signature, IHDR and the IDAT header.
    uint32_t at = 8 + 25 + 8 + 2;
    uint32_t blocks = 0;
    uint32_t stored = 0;
    for (bool last = false; !last;) {
        last = encoded[at] == 1;
        const uint32_t length = uint32_t(encoded[at + 1]) | uint32_t(encoded[at + 2]) << 8;
        CHECK(uint8_t(~encoded[at + 1]) == encoded[at + 3]);
        CHECK(uint8_t(~encoded[at + 2]) == encoded[at + 4]);
        at += 5 + length;
        stored += length;
        ++blocks;
    }
    CHECK(blocks == 3);
    CHECK(stored == 600 * (64 * 4 + 1));
    checkChunks(encoded);
    CHECK(decode(encoded, 64, 600) == pixels);
