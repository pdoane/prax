    uint16_t pixels[2] = {};
    const PrPixels output{reinterpret_cast<uint8_t*>(pixels), 4, {1, 1}};
    REQUIRE(prImageDecoderRead(decoder, 0, output) == PrStatus_Ok);
    CHECK(pixels[0] == 0x1234);
    CHECK(pixels[1] == 65535);
    REQUIRE(prImageDecoderRead(decoder, 1, output) == PrStatus_Ok);
