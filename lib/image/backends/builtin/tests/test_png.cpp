// Returns a PNG with `extra` inserted between the header chunk and the pixel data.
std::vector<uint8_t> withChunk(const std::vector<uint8_t>& png, const std::vector<uint8_t>& extra) {
    const size_t afterHeader = 8 + 25;
    std::vector<uint8_t> out(png.begin(), png.begin() + long(afterHeader));
    out.insert(out.end(), extra.begin(), extra.end());
    out.insert(out.end(), png.begin() + long(afterHeader), png.end());
    return out;
}

// Returns a physical pixel dimensions chunk of `perMeter` pixels along both axes.
std::vector<uint8_t> physChunk(uint32_t perMeter, uint8_t unit) {
    std::vector<uint8_t> data;
    appendBe32(data, perMeter);
    appendBe32(data, perMeter);
    data.push_back(unit);
    return chunk("pHYs", data);
}

// Returns an eXIf chunk that holds a big-endian TIFF header with one orientation entry.
std::vector<uint8_t> exifChunk(uint8_t orientation) {
    std::vector<uint8_t> data = {'M', 'M', 0, 42, 0, 0, 0, 8, 0, 1, 0x01, 0x12, 0, 3};
    appendBe32(data, 1);
    data.insert(data.end(), {0, orientation, 0, 0});
    appendBe32(data, 0);
    return chunk("eXIf", data);
}

std::vector<uint8_t> rawExifText(uint8_t orientation) {
    const std::vector<uint8_t> exif = exifChunk(orientation);
    std::vector<uint8_t> data = {'E', 'x', 'i', 'f', 0, 0};
    data.insert(data.end(), exif.begin() + 8, exif.end() - 4);
    const std::string header = "\nexif\n    " + std::to_string(data.size()) + "\n";
    std::vector<uint8_t> text(header.begin(), header.end());
    constexpr char kHex[] = "0123456789abcdef";
    for (size_t index = 0; index < data.size(); ++index) {
        if (index != 0 && index % 12 == 0)
            text.push_back('\n');
        text.push_back(uint8_t(kHex[data[index] >> 4]));
        text.push_back(uint8_t(kHex[data[index] & 15]));
    }
    text.push_back('\n');
    return text;
}

std::vector<uint8_t> rawExifChunk(const std::vector<uint8_t>& text, bool compressed) {
    constexpr char kKeyword[] = "Raw profile type exif";
    std::vector<uint8_t> data(kKeyword, kKeyword + sizeof(kKeyword));
    if (compressed) {
        data.push_back(0);
        const std::vector<uint8_t> stream = stored(text);
        data.insert(data.end(), stream.begin(), stream.end());
    } else {
        data.insert(data.end(), text.begin(), text.end());
    }
    return chunk(compressed ? "zTXt" : "tEXt", data);
}

// Returns each gray sample repeated over the three color channels, opaque.
std::vector<uint8_t> grayPixels(const std::vector<uint8_t>& samples) {
    std::vector<uint8_t> out;
    for (uint8_t sample : samples) {
        out.insert(out.end(), {sample, sample, sample, 0xFF});
    }
    return out;
}

// Checks the CRC of each chunk.
void checkChunks(const std::vector<uint8_t>& encoded) {
    for (size_t chunkAt = 8; chunkAt < encoded.size();) {
        const size_t length = prMemReadBeU32(encoded.data() + chunkAt);
        REQUIRE(length + 12 <= encoded.size() - chunkAt);
        const std::vector<uint8_t> typed(encoded.data() + chunkAt + 4, encoded.data() + chunkAt + 8 + length);
        CHECK(prMemReadBeU32(encoded.data() + chunkAt + 8 + length) == crc32(typed));
        chunkAt += length + 12;
    }
}

// Returns the PNG with a chunk of `type` and `body` inserted after IHDR.
std::vector<uint8_t> withChunk(const std::vector<uint8_t>& png, const char* type, const std::vector<uint8_t>& body) {
    std::vector<uint8_t> chunk(4, 0);
    uint32_t length = uint32_t(body.size());
    for (uint32_t i = 0; i < 4; ++i)
        chunk[i] = uint8_t(length >> (24 - 8 * i));
    chunk.insert(chunk.end(), type, type + 4);
    chunk.insert(chunk.end(), body.begin(), body.end());
    uint32_t crc = prCrc32Update(0, PrByteView{chunk.data() + 4, chunk.size() - 4});
    for (uint32_t i = 0; i < 4; ++i)
        chunk.push_back(uint8_t(crc >> (24 - 8 * i)));
    std::vector<uint8_t> out(png.begin(), png.begin() + 33);
    out.insert(out.end(), chunk.begin(), chunk.end());
    out.insert(out.end(), png.begin() + 33, png.end());
    return out;
}

// Returns the space that the PNG's color names, or PrColorSpace_Count if the color is not named.
PrColorSpace namedSpace(const std::vector<uint8_t>& png) {
    PrImageDecoder* decoder = testImageOpen(png.data(), png.size());
    REQUIRE(decoder != nullptr);
    const PrImageColor color = prImageDecoderInfo(decoder)->format.color;
    prImageDecoderDestroy(decoder);
    return color.encoding == PrImageColorEncoding_Named ? color.space : PrColorSpace_Count;
}

