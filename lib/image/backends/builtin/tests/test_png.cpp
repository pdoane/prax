// Returns a physical pixel dimensions chunk of `perMeter` pixels along both axes.
Array<uint8_t> physChunk(uint32_t perMeter, uint8_t unit) {
    Array<uint8_t> data;
    appendBe32(data, perMeter);
    appendBe32(data, perMeter);
    data.push(unit);
    return chunk("pHYs", data);
}

// Returns an eXIf chunk that holds a big-endian TIFF header with one orientation entry.
Array<uint8_t> exifChunk(uint8_t orientation) {
    Array<uint8_t> data({'M', 'M', 0, 42, 0, 0, 0, 8, 0, 1, 0x01, 0x12, 0, 3});
    appendBe32(data, 1);
    data.append(Array<uint8_t>({0, orientation, 0, 0}).span());
    appendBe32(data, 0);
    return chunk("eXIf", data);
}

Array<uint8_t> rawExifText(uint8_t orientation) {
    const Array<uint8_t> exif = exifChunk(orientation);
    Array<uint8_t> data({'E', 'x', 'i', 'f', 0, 0});
    data.append(sliceBytes(exif, 8, exif.count() - 12));
    Array<uint8_t> text = copyBytes(prStringBytes(format("\nexif\n    {}\n", data.count())));
    constexpr char kHex[] = "0123456789abcdef";
    for (uint32_t index = 0; index < data.count(); ++index) {
        if (index != 0 && index % 12 == 0)
            text.push('\n');
        text.push(uint8_t(kHex[data[index] >> 4]));
        text.push(uint8_t(kHex[data[index] & 15]));
    }
    text.push('\n');
    return text;
}

Array<uint8_t> rawExifChunk(PrByteView text, bool compressed) {
    constexpr char kKeyword[] = "Raw profile type exif";
    Array<uint8_t> data = copyBytes(prStringBytes(PrStringView(kKeyword, sizeof(kKeyword))));
    if (compressed) {
        data.push(0);
        data.append(stored(text).span());
    } else {
        data.append(text);
    }
    return chunk(compressed ? "zTXt" : "tEXt", data);
}

// Returns each gray sample repeated over the three color channels, opaque.
Array<uint8_t> grayPixels(PrByteView samples) {
    Array<uint8_t> out;
    for (uint8_t sample : samples) {
        out.append(Array<uint8_t>({sample, sample, sample, 0xFF}).span());
    }
    return out;
}

// Checks the CRC of each chunk.
void checkChunks(const Array<uint8_t>& encoded) {
    for (uint32_t chunkAt = 8; chunkAt < encoded.count();) {
        const uint32_t length = prMemReadBeU32(encoded.data() + chunkAt);
        REQUIRE(length + 12 <= encoded.count() - chunkAt);
        const PrByteView typed = sliceBytes(encoded, chunkAt + 4, length + 4);
        CHECK(prMemReadBeU32(encoded.data() + chunkAt + 8 + length) == crc32(typed));
        chunkAt += length + 12;
    }
}

// Returns the PNG with a chunk of `type` and `body` inserted after IHDR.
Array<uint8_t> withChunk(PrByteView png, const char* type, PrByteView body) {
    Array<uint8_t> chunk(4);
    uint32_t length = uint32_t(body.size);
    for (uint32_t i = 0; i < 4; ++i)
        chunk[i] = uint8_t(length >> (24 - 8 * i));
    chunk.append(prStringBytes(PrStringView(type, 4)));
    chunk.append(body);
    uint32_t crc = prCrc32Update(0, PrByteView{chunk.data() + 4, chunk.count() - 4});
    for (uint32_t i = 0; i < 4; ++i)
        chunk.push(uint8_t(crc >> (24 - 8 * i)));
    Array<uint8_t> out = copyBytes(sliceBytes(png, 0, 33));
    out.append(chunk.span());
    out.append(sliceBytes(png, 33, png.size - 33));
    return out;
}

// Returns the space that the PNG's color names, or PrColorSpace_Count if the color is not named.
PrColorSpace namedSpace(PrByteView png) {
    PrImageDecoder* decoder = testImageOpen(png.data, png.size);
    REQUIRE(decoder != nullptr);
    const PrImageColor color = prImageDecoderInfo(decoder)->format.color;
    prImageDecoderDestroy(decoder);
    return color.encoding == PrImageColorEncoding_Named ? color.space : PrColorSpace_Count;
}

