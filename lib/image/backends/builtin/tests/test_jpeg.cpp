// Returns the largest component difference between a decode and its reference, and the offset at which it occurs.
uint32_t largestDifference(const std::vector<uint8_t>& decoded,
                           const std::vector<uint8_t>& reference, uint32_t* outIndex) {
    uint32_t largest = 0;
    for (size_t index = 0; index < reference.size(); ++index) {
        const int difference = int(decoded[index]) - int(reference[index]);
        const uint32_t distance = uint32_t(difference < 0 ? -difference : difference);
        if (distance > largest) {
            largest = distance;
            *outIndex = uint32_t(index);
        }
    }
    return largest;
}

// Returns a frame header of `marker` over one component, with no tables and no scan. It is enough for the decoder to
// reach the frame and reject its coding.
std::vector<uint8_t> frameOf(uint8_t marker) {
    return {0xFF, 0xD8, 0xFF, marker, 0x00, 0x0B, 0x08, 0x00, 0x08,
            0x00, 0x08, 0x01, 0x01,   0x11, 0x00, 0xFF, 0xD9};
}

// Pushes a big-endian or little-endian integer of `width` bytes.
void pushInteger(std::vector<uint8_t>& bytes, uint64_t value, uint32_t width, bool bigEndian) {
    for (uint32_t index = 0; index < width; ++index) {
        const uint32_t shift = bigEndian ? (width - 1 - index) * 8 : index * 8;
        bytes.push_back(uint8_t((value >> shift) & 0xFF));
    }
}

// Pushes one image file directory entry: tag, field type, a count of one, and the four value bytes, which hold a short
// in the first two.
void pushEntry(std::vector<uint8_t>& tiff, uint32_t tag, uint32_t type, uint32_t value,
               bool bigEndian) {
    pushInteger(tiff, tag, 2, bigEndian);
    pushInteger(tiff, type, 2, bigEndian);
    pushInteger(tiff, 1, 4, bigEndian);
    if (type == 3) {
        pushInteger(tiff, value, 2, bigEndian);
        pushInteger(tiff, 0, 2, bigEndian);
    } else {
        pushInteger(tiff, value, 4, bigEndian);
    }
}

// Returns an Exif application segment over a TIFF header with `entries` directory entries, followed by `trailing` bytes
// that a rational value points at.
std::vector<uint8_t> exifSegment(const std::vector<std::vector<uint8_t>>& entries,
                                 const std::vector<uint8_t>& trailing, bool bigEndian) {
    std::vector<uint8_t> tiff;
    tiff.push_back(bigEndian ? 'M' : 'I');
    tiff.push_back(bigEndian ? 'M' : 'I');
    pushInteger(tiff, 42, 2, bigEndian);
    pushInteger(tiff, 8, 4, bigEndian);
    pushInteger(tiff, entries.size(), 2, bigEndian);
    for (const std::vector<uint8_t>& entry : entries) {
        tiff.insert(tiff.end(), entry.begin(), entry.end());
    }
    pushInteger(tiff, 0, 4, bigEndian);
    tiff.insert(tiff.end(), trailing.begin(), trailing.end());

    std::vector<uint8_t> segment = {0xFF, 0xE1};
    pushInteger(segment, tiff.size() + 8, 2, true);
    segment.insert(segment.end(), {'E', 'x', 'i', 'f', 0, 0});
    segment.insert(segment.end(), tiff.begin(), tiff.end());
    return segment;
}

// Returns the offset of a rational value: after the header, the entry count, the entries and the offset of the next
// directory.
uint32_t rationalOffset(size_t entryCount) {
    return uint32_t(8 + 2 + entryCount * 12 + 4);
}

std::vector<uint8_t> orientationSegment(uint8_t orientation, bool bigEndian) {
    std::vector<uint8_t> entry;
    pushEntry(entry, 0x0112, 3, orientation, bigEndian);
    return exifSegment({entry}, {}, bigEndian);
}

// Returns a JFIF application segment that specifies a pixel density in `units`: one for the inch, two for the
// centimetre.
std::vector<uint8_t> jfifSegment(uint8_t units, uint32_t density) {
    std::vector<uint8_t> segment = {0xFF, 0xE0, 0, 16, 'J', 'F', 'I', 'F', 0, 1, 2, units};
    pushInteger(segment, density, 2, true);
    pushInteger(segment, density, 2, true);
    segment.insert(segment.end(), {0, 0});
    return segment;
}

// Returns the bytes of the vector with `segment` inserted between the start marker and the segments that the encoder
// wrote.
std::vector<uint8_t> withSegment(const Vector& vector, const std::vector<uint8_t>& segment) {
    std::vector<uint8_t> bytes = {0xFF, 0xD8};
    bytes.insert(bytes.end(), segment.begin(), segment.end());
    bytes.insert(bytes.end(), vector.bytes.begin() + 2, vector.bytes.end());
    return bytes;
}

// Returns the pixels that an Exif orientation displays, computed directly from the stored rows.
std::vector<uint8_t> orientedPixels(const std::vector<uint8_t>& pixels, uint32_t storedWidth,
                                    uint32_t storedHeight, uint8_t orientation) {
    const bool swaps = orientation >= 5;
    const uint32_t width = swaps ? storedHeight : storedWidth;
    const uint32_t height = swaps ? storedWidth : storedHeight;
    std::vector<uint8_t> out(pixels.size(), 0);
    for (uint32_t y = 0; y < height; ++y) {
        for (uint32_t x = 0; x < width; ++x) {
            uint32_t sourceX = x;
            uint32_t sourceY = y;
            switch (orientation) {
                case 2:
                    sourceX = storedWidth - 1 - x;
                    break;
                case 3:
                    sourceX = storedWidth - 1 - x;
                    sourceY = storedHeight - 1 - y;
                    break;
                case 4:
                    sourceY = storedHeight - 1 - y;
                    break;
                case 5:
                    sourceX = y;
                    sourceY = x;
                    break;
                case 6:
                    sourceX = y;
                    sourceY = storedHeight - 1 - x;
                    break;
                case 7:
                    sourceX = storedWidth - 1 - y;
                    sourceY = storedHeight - 1 - x;
                    break;
                case 8:
                    sourceX = storedWidth - 1 - y;
                    sourceY = x;
                    break;
                default:
                    break;
            }
            const size_t source = (size_t(sourceY) * storedWidth + sourceX) * 4;
            const size_t target = (size_t(y) * width + x) * 4;
            for (uint32_t channel = 0; channel < 4; ++channel) {
                out[target + channel] = pixels[source + channel];
            }
        }
    }
    return out;
}

