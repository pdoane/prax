// Returns the largest component difference between a decode and its reference, and the offset at which it occurs.
uint32_t largestDifference(Span<const uint8_t> decoded, Span<const uint8_t> reference, uint32_t* outIndex) {
    uint32_t largest = 0;
    for (uint32_t index = 0; index < reference.count(); ++index) {
        const uint32_t distance = absDifference(decoded[index], reference[index]);
        if (distance > largest) {
            largest = distance;
            *outIndex = index;
        }
    }
    return largest;
}

// Returns a frame header of `marker` over one component, with no tables and no scan. It is enough for the decoder to
// reach the frame and reject its coding.
Array<uint8_t> frameOf(uint8_t marker) {
    return Array<uint8_t>({
        0xFF, 0xD8, 0xFF, marker, 0x00, 0x0B, 0x08, 0x00, 0x08, 0x00, 0x08, 0x01, 0x01,   0x11, 0x00,
        0xFF, 0xD9,
    });
}

// Pushes a big-endian or little-endian integer of `width` bytes.
void pushInteger(Array<uint8_t>& bytes, uint64_t value, uint32_t width, bool bigEndian) {
    for (uint32_t index = 0; index < width; ++index) {
        const uint32_t shift = bigEndian ? (width - 1 - index) * 8 : index * 8;
        bytes.push(uint8_t((value >> shift) & 0xFF));
    }
}

// Pushes one image file directory entry: tag, field type, a count of one, and the four value bytes, which hold a short
// in the first two.
void pushEntry(Array<uint8_t>& tiff, uint32_t tag, uint32_t type, uint32_t value, bool bigEndian) {
    pushInteger(tiff, tag, 2, bigEndian);
    pushInteger(tiff, type, 2, bigEndian);
    pushInteger(tiff, 1, 4, bigEndian);
    if (type == 3) {
        pushInteger(tiff, value, 2, bigEndian);
        pushInteger(tiff, 0, 2, bigEndian);
    } else {
        pushInteger(tiff, value, 4, bigEndian);
    }
}

// Returns an Exif application segment over a TIFF header with `entries` directory entries, followed by `trailing` bytes
// that a rational value points at.
Array<uint8_t> exifSegment(Span<const Array<uint8_t>> entries, const Array<uint8_t>& trailing, bool bigEndian) {
    Array<uint8_t> tiff;
    tiff.push(bigEndian ? 'M' : 'I');
    tiff.push(bigEndian ? 'M' : 'I');
    pushInteger(tiff, 42, 2, bigEndian);
    pushInteger(tiff, 8, 4, bigEndian);
    pushInteger(tiff, entries.count(), 2, bigEndian);
    for (const Array<uint8_t>& entry : entries) {
        tiff.append(entry.span());
    }
    pushInteger(tiff, 0, 4, bigEndian);
    tiff.append(trailing.span());

    Array<uint8_t> segment({0xFF, 0xE1});
    pushInteger(segment, tiff.count() + 8, 2, true);
    segment.append(Array<uint8_t>({'E', 'x', 'i', 'f', 0, 0}).span());
    segment.append(tiff.span());
    return segment;
}

// Returns the offset of a rational value: after the header, the entry count, the entries and the offset of the next
// directory.
uint32_t rationalOffset(size_t entryCount) {
    return uint32_t(8 + 2 + entryCount * 12 + 4);
}

Array<uint8_t> orientationSegment(uint8_t orientation, bool bigEndian) {
    Array<uint8_t> entry;
    pushEntry(entry, 0x0112, 3, orientation, bigEndian);
    return exifSegment(Span<const Array<uint8_t>>(&entry, 1), {}, bigEndian);
}

// Returns a JFIF application segment that specifies a pixel density in `units`: one for the inch, two for the
// centimetre.
Array<uint8_t> jfifSegment(uint8_t units, uint32_t density) {
    Array<uint8_t> segment({0xFF, 0xE0, 0, 16, 'J', 'F', 'I', 'F', 0, 1, 2, units});
    pushInteger(segment, density, 2, true);
    pushInteger(segment, density, 2, true);
    segment.append(Array<uint8_t>({0, 0}).span());
    return segment;
}

// Returns the bytes of the vector with `segment` inserted between the start marker and the segments that the encoder
// wrote.
Array<uint8_t> withSegment(const Vector& vector, const Array<uint8_t>& segment) {
    Array<uint8_t> bytes({0xFF, 0xD8});
    bytes.append(segment.span());
    bytes.append(vector.bytes.from(2));
    return bytes;
}

// Returns the pixels that an Exif orientation displays, computed directly from the stored rows.
Array<uint8_t> orientedPixels(Span<const uint8_t> pixels, uint32_t storedWidth,
        uint32_t storedHeight, uint8_t orientation) {
    const bool swaps = orientation >= 5;
    const uint32_t width = swaps ? storedHeight : storedWidth;
    const uint32_t height = swaps ? storedWidth : storedHeight;
    Array<uint8_t> out(pixels.count());
    for (uint32_t y = 0; y < height; ++y) {
        for (uint32_t x = 0; x < width; ++x) {
            uint32_t sourceX = x;
            uint32_t sourceY = y;
            switch (orientation) {
                case 2:
                    sourceX = storedWidth - 1 - x;
                    break;
                case 3:
                    sourceX = storedWidth - 1 - x;
                    sourceY = storedHeight - 1 - y;
                    break;
                case 4:
                    sourceY = storedHeight - 1 - y;
                    break;
                case 5:
                    sourceX = y;
                    sourceY = x;
                    break;
                case 6:
                    sourceX = y;
                    sourceY = storedHeight - 1 - x;
                    break;
                case 7:
                    sourceX = storedWidth - 1 - y;
                    sourceY = storedHeight - 1 - x;
                    break;
                case 8:
                    sourceX = storedWidth - 1 - y;
                    sourceY = x;
                    break;
                default:
                    break;
            }
            const uint32_t source = (sourceY * storedWidth + sourceX) * 4;
            const uint32_t target = (y * width + x) * 4;
            for (uint32_t channel = 0; channel < 4; ++channel) {
                out[target + channel] = pixels[source + channel];
            }
        }
    }
    return out;
}

// Returns `image` with an Exif segment inserted after its start-of-image marker. The second directory of the segment
// stores `thumbnail` as a JPEG thumbnail.
Array<uint8_t> withThumbnail(Span<const uint8_t> image, Span<const uint8_t> thumbnail) {
    // The TIFF structure is a header, an empty first directory, the three fields of the second directory, and the
    // thumbnail at offset 56. The first directory links to the second at offset 14.
    Array<uint8_t> tiff;
    const uint8_t header[] = {'M', 'M', 0, 42, 0, 0, 0, 8};
    tiff.append(Span<const uint8_t>(header));
    pushInteger(tiff, 0, 2, true);
    pushInteger(tiff, 14, 4, true);
    pushInteger(tiff, 3, 2, true);
    const uint32_t fields[3][3] = {{0x0103, 3, 6u << 16}, {0x0201, 4, 56}, {0x0202, 4, thumbnail.count()}};
    for (const uint32_t* field : fields) {
        pushInteger(tiff, field[0], 2, true);
        pushInteger(tiff, field[1], 2, true);
        pushInteger(tiff, 1, 4, true);
        pushInteger(tiff, field[2], 4, true);
    }
    pushInteger(tiff, 0, 4, true);
    REQUIRE(tiff.count() == 56);
    tiff.append(thumbnail);
    Array<uint8_t> file;
    file.append(Span<const uint8_t>(image.begin(), 2));
    const uint8_t marker[] = {0xFF, 0xE1};
    file.append(Span<const uint8_t>(marker));
    pushInteger(file, 2 + 6 + tiff.count(), 2, true);
    const uint8_t exif[] = {'E', 'x', 'i', 'f', 0, 0};
    file.append(Span<const uint8_t>(exif));
    file.append(tiff.span());
    file.append(Span<const uint8_t>(image.begin() + 2, image.count() - 2));
    return file;
}

