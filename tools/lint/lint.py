# type, or a keyword that a block follows. A brace after anything else opens data, an initializer list.
CODE_BRACE = re.compile(r"(?:[)\]}^:]|\b(?:mutable|noexcept|const|override|final|else|do|try|[A-Z][A-Z0-9]*_[A-Z0-9_]+)"
                        r"|->\s*[\w:<>,*& ]+)\s*$")

# A line that ends a statement without a semicolon: a macro that expands to declarations, or a template's header, which
# may end with its requires-clause.
UNTERMINATED_STATEMENT = re.compile(r"[A-Z][A-Z0-9_]*(?:\(.*\))?|template\s*<.*>(?:\s+requires\b.*)?")

# The first line of a statement whose body may follow it without braces.
CONTROL_HEAD = re.compile(r"(?:\}\s*)?(?:if|for|while|else|do|switch)\b")

# A binary operator that begins a line. It belongs at the end of the line before it, where the line reads as unfinished.
LEADING_OPERATOR = re.compile(r"(?:&&|\|\||<<=|>>=|[-+*/%&|^=!<>]=|<<|>>|[-+*/%&|^<>?:=])(?=\s)")

# What a line ends with when a binary operator may follow it: an operand.
OPERAND_END = re.compile(r"[\w)\]}\"']$")

# An initializer list's item that is designated, or that is itself a list whose items are.
DESIGNATED_ITEM = re.compile(r"\{*\s*[.\[]")

# The end of a string literal whose last escape, a hex or an octal one, would read on into a literal joined to it.
ESCAPE_END = re.compile(r'\\(?:x[0-9A-Fa-f]*|[0-7]{1,2})"$')

# The invocations of macros, whose expansions the layout cannot see.
MACRO_CALL = re.compile(r"(?:[A-Z][A-Z0-9_]*(?:\s*\([\s\S]*\))?\s*)+")

# Where a line may break: after a comma, or after a binary operator between spaces.
BREAK_AFTER = re.compile(r"(?:,|(?<= )(?:&&|\|\||[-+*/%&|^=!<>]=|<<|>>|[-+*/%&|^<>?:=]))( +)(?=\S)")

# How loosely each operator that a line may break after binds: a line that runs too long breaks after the loosest, so
# that each of its lines holds whole operands.
BREAK_RANK = {op: rank for rank, ops in enumerate([
    [","], ["=", "+=", "-=", "*=", "/=", "%=", "&=", "|=", "^=", "<<=", ">>="], ["?", ":"], ["||"], ["&&"], ["|"],
    ["^"], ["&"], ["==", "!="], ["<", ">", "<=", ">="], ["<<", ">>"], ["+", "-"], ["*", "/", "%"]]) for op in ops}

# A line that ends with a label rather than an operator: a case label, an access specifier, or a goto's label.
LABEL = re.compile(r"case\b.*:|(?:default|public|private|protected)\s*:|[A-Za-z_]\w*:")


def raw_string_lines(text):
    """Returns the numbers of the lines that begin inside a raw string literal, whose text is not code."""
    lines = set()
    for start, end, comment in c_literals(text):
        if not comment and RAW_STRING.match(text, start):
            lines.update(range(line_of(text, start) + 1, line_of(text, end) + 1))
    return lines


def layout(text):
    """Returns how C, C++ or Objective-C `text` is laid out, as (lines, braces).

    `lines` holds (number, own, expected, role) for each line that the rules decide. Code is indented four spaces a
    level:

    - A line inside an expression's parentheses, brackets or initializer braces is indented one level past the line
      that opened the innermost of them, or at that line's own indentation if it begins by closing it.
    - A line that begins a statement is indented one level past its block's opening: the first line of the statement
      that opens the block, or, for a lambda's or an Objective-C block's body, the line that holds its brace. A closing
      brace and an access specifier sit at the opening's own indentation. A switch's case labels are indented one level,
      and their statements two. The contents of a namespace and of C linkage are not indented. An enumeration's items
      each begin a line.
    - A line that continues a statement outside any open parenthesis is indented one level past the statement's first
      line.
    - The head of a block or of a control statement, which a body follows, is indented one level further where it
      continues, so that it does not line up with the body.

    A line's role is `start` if it begins a statement, `item` if it begins an item of an initializer list, `close` if
    it begins by closing an expression's bracket, `body` if it is the body of a control statement without braces, and
    `continuation` if it continues the line before it. A comment on a line of its own is decided only within an
    expression's brackets, and has no role. Preprocessor directives, and the lines of a raw string literal, are left
    alone. Each line is measured against the indentation that the lines before it should have, so that one misplaced
    line does not misplace the lines that follow it.

    `braces` holds (open, close), the offsets in `text` of each initializer list's braces."""
    code = mask_non_code(text)
    raw = raw_string_lines(text)
    lines = []
    braces = []
    stack = []          # each open bracket: its kind, its base indentation, the statement it opened in, its offset,
                        # and whether an item within it has begun a line
    previous = ""       # the last line of code, stripped, with its literals
    closes_data = False # true if that line ends by closing an initializer list, which does not end a statement
    statement = 0       # the index in `lines` of the line that began the current statement
    deepened = -1       # the index of the statement whose head has been indented further
    start = 0           # the indentation of the line that began the current statement
    head = ""           # that line, stripped
    directive = False   # true while a preprocessor directive continues onto the next line
    offset = 0          # the offset of the current line in `text`
    commented = mask_comments(text).split("\n")
    closed_kind = None  # the kind of the bracket that closed last

    def deepen():
        """Indents the continuation lines of the current statement's head one level further, once."""
        nonlocal deepened
        if deepened == statement:
            return
        deepened = statement
        for index in range(statement + 1, len(lines)):
            number, own, expected, role = lines[index]
            if expected is not None and expected > start:
                lines[index] = (number, own, expected + 4, role)

    for number, (line, original) in enumerate(zip(code.split("\n"), text.split("\n")), 1):
        at, offset = offset, offset + len(line) + 1
        stripped = line.strip()
        own = len(original) - len(original.lstrip())
        leading = original[own:own + 1]  # the line's first character, which may begin a literal that the mask hides
        if directive or stripped.startswith("#"):
            directive = original.rstrip().endswith("\\")
            previous = ""
            continue
        # A line that begins inside a raw string keeps its indentation, which is the string's text. What follows the
        # string's end is still code: its brackets close what the string's line opened, and it may end the statement.
        literal = number in raw
        top = stack[-1] if stack else None
        inner = top is not None and top[0] in ("expression", "data")
        # A line of only a string literal is code, though the mask leaves it blank.
        if not stripped and not literal and original.lstrip()[:1] != '"':
            if original.lstrip().startswith("//") and inner:
                lines.append((number, own, top[1] + 4, None))
            continue
        expected = None
        role = None
        if literal:
            pass
        elif inner:
            if leading in ")]}":
                expected = top[1]
                role = "close"
            elif previous.endswith((",", "(", "[", "{")):
                # An item that begins a line: what continues it is indented past it.
                expected = top[1] + 4
                role = "item" if top[0] == "data" else "continuation"
                top[5] = True
            else:
                expected = top[1] + (8 if top[5] else 4)
                role = "continuation"
        else:
            ended = (previous == "" or previous.endswith((";", "{")) or (previous.endswith("}") and not closes_data)
                     or LABEL.fullmatch(previous) is not None
                     or previous.startswith("@") or UNTERMINATED_STATEMENT.fullmatch(previous) is not None)
            if top is not None and top[0] == "list":
                ended = ended or previous.endswith(",")
            if ended or leading == "}":
                if top is None:
                    expected = 0
                elif leading == "}" or ACCESS_LABEL.match(stripped) or top[0] == "flat":
                    expected = top[1]
                elif top[0] == "switch":
                    expected = top[1] + (4 if CASE_LABEL.match(stripped) else 8)
                else:
                    expected = top[1] + 4
                role = "start"
                if leading != "}":
                    start = expected
                    head = original.strip()
            elif leading == "{" and CODE_BRACE.search(previous):
                # A brace on a line of its own that opens a function's body sits at the function's indentation.
                expected = start
                role = "start"
            else:
                expected = start + 4
                role = "body" if CONTROL_HEAD.match(head) else "continuation"
                if role == "body":
                    # A body without braces begins a statement of its own, whose continuations are indented past it.
                    deepen()
                    start = expected
                    head = original.strip()
        if not literal:
            if role in ("start", "body"):
                statement = len(lines)
            lines.append((number, own, expected, role))
        indent = expected if expected is not None else own
        for column, character in enumerate(line):
            inside = bool(stack) and stack[-1][0] in ("expression", "data")
            if character in "([":
                stack.append(["expression", indent, start, head, at + column, False])
            elif character == "{":
                if CODE_BRACE.search(line[:column]) or (not inside and CODE_HEAD.match(head)):
                    if UNINDENTED_BLOCK.match(head) and not inside:
                        kind = "flat"
                    elif SWITCH_BLOCK.match(head) and not inside:
                        kind = "switch"
                    elif ENUM_HEAD.match(head) and not inside:
                        kind = "list"
                    else:
                        kind = "code"
                    base = indent if inside else start
                    stack.append([kind, base, start, head, at + column, False])
                    if not inside:
                        deepen()
                elif not inside and column == own and (role == "start" or CODE_BRACE.search(previous)):
                    # A brace on a line of its own that begins a statement opens a compound statement.
                    stack.append(["code", indent, start, head, at + column, False])
                    deepen()
                else:
                    stack.append(["data", indent, start, head, at + column, False])
            elif character in ")]}" and stack:
                closed = stack.pop()
                closed_kind = closed[0]
                if closed[0] == "data" and character == "}":
                    braces.append((closed[4], at + column))
                if closed[0] not in ("expression", "data"):
                    start, head = closed[2], closed[3]
        if literal and stripped:
            previous = stripped
        elif not literal and commented[number - 1].strip():
            previous = commented[number - 1].strip()
        else:
            continue
        closes_data = stripped.endswith("}") and closed_kind == "data"
    return lines, braces


def mask_comments(text):
    """Returns the text with its comments hidden, and its literals kept, without changing offsets or line numbers."""
    return NON_CODE.sub(lambda match: blank(match.group(0)) if match.group(0).startswith(("//", "/*"))
        else match.group(0), text)


def layout_problems(text):
    """Returns the problems with how C, C++ or Objective-C `text` breaks its lines, as (number, check, message, edits),
    where each edit, (start, end, replacement), replaces a span of `text`. The edits of one check do not overlap, and
    applying them fixes its problems. A line reaches toward the column limit before it breaks:

    - `operator`: a binary operator that a line breaks at ends the line, rather than beginning the next.
    - `wrap`: a line that continues the line before it, and fits on it, is part of it, and a string literal that
      continues another joins it as one literal. The body of a control statement begins a line of its own, and so do
      an item of an initializer list that begins one and the text after a string literal that ends in a line break.
    - `initializer`: an initializer list that fits on one line is on one line. One that does not begins its items on
      the line after its opening brace, ends its last item with a comma, and closes on a line of its own. If its items
      are designated, or are lists whose items are, each is on a line of its own."""
    lines, braces = layout(text)
    code = mask_non_code(text)
    commented = mask_comments(text)
    comments = commented.split("\n")
    originals = text.split("\n")
    raw = raw_string_lines(text)
    starts = [0]
    for line in originals:
        starts.append(starts[-1] + len(line) + 1)
    roles = {number: role for number, _, _, role in lines}
    problems = []

    def code_end(number):
        """Returns the length of a line's code, or None if the line cannot be extended: it has a comment after its
        code, or no code at all."""
        if roles.get(number) is None:
            return None
        end = len(comments[number - 1].rstrip())
        if end == 0 or originals[number - 1].rstrip() != originals[number - 1][:end]:
            return None
        return end

    report = Report()
    check_line_length(report, "x.cpp", text, c_literals(text))
    conditionals = conditional_spans(code) if report.problems else []
    for _, number, _, _ in report.problems:
        own = len(originals[number - 1]) - len(originals[number - 1].lstrip())
        if roles.get(number) is None:
            continue
        masked = code.split("\n")[number - 1]
        end = len(masked.rstrip())
        breaks = []
        at = starts[number - 1]
        for found in BREAK_AFTER.finditer(masked):
            # A conditional expression stays on one line.
            inside = any(s < at + found.start(1) < e for s, e in conditionals)
            if own < found.start(1) <= LINE_LIMIT and found.end(1) < end and not inside:
                depth = sum(masked[:found.start(1)].count(c) for c in "([{") - \
                    sum(masked[:found.start(1)].count(c) for c in ")]}")
                operator = masked[found.start():found.start(1)].strip()
                breaks.append((depth, BREAK_RANK.get(operator, len(BREAK_RANK)), -found.start(1), found))
        if breaks:
            found = min(breaks, key=lambda b: b[:3])[3]
            # The mask blanks literals, so only the spaces that the line itself holds are the break.
            line = originals[number - 1]
            spaces = len(line[found.start(1):]) - len(line[found.start(1):].lstrip(" "))
            problems.append((number, "long", "runs past the limit",
                [(at + found.start(1), at + found.start(1) + spaces, "\n")]))

    for number, own, _, role in lines:
        if role != "continuation" or number == 1:
            continue
        line = originals[number - 1]
        match = LEADING_OPERATOR.match(line, own)
        end = code_end(number - 1)
        if match and end is not None and OPERAND_END.search(comments[number - 2][:end]):
            operator = match.group(0)
            after = len(line) - len(line[match.end():].lstrip())
            at = starts[number - 2]
            edits = [(at + end, at + end, " " + operator), (starts[number - 1] + own, starts[number - 1] + after, "")]
            # If the operator does not fit on the line before, that line breaks sooner, at its last break that leaves
            # room for what follows the break and the operator together.
            if not within_limit(originals[number - 2][:end] + " " + operator):
                previous = code.split("\n")[number - 2][:end]
                indent = len(previous) - len(previous.lstrip()) + 4
                breaks = [found for found in BREAK_AFTER.finditer(previous)
                          if indent + end - found.end() + 1 + len(operator) <= LINE_LIMIT]
                if not breaks:
                    continue
                edits.append((at + breaks[-1].start(1), at + breaks[-1].end(1), "\n"))
            problems.append((number, "operator", "begins with %s, which ends the line before it" % operator, edits))

    merged = {}             # each line's text, with the lines joined to it
    for number, own, _, role in lines:
        line = originals[number - 1].rstrip()
        merged[number] = line
        if role not in ("continuation", "close") or number == 1 or line[own] == "}":
            continue
        end = code_end(number - 1)
        if end is None:
            continue
        before = comments[number - 2][:end]
        if line[own] == "{" and not before.endswith(("(", "[", ",", "=")):
            continue
        if LEADING_OPERATOR.match(line, own) and OPERAND_END.search(before):
            continue
        # A line that leaves a bracket open joins only a line indented as far as it, so that what the bracket holds
        # is not indented further.
        masked = code.split("\n")[number - 1]
        opened = sum(masked.count(c) for c in "([{") - sum(masked.count(c) for c in ")]}")
        if opened > 0 and len(originals[number - 2]) - len(originals[number - 2].lstrip()) > own:
            continue
        # A string literal that ends a line of text, as embedded documents do, keeps the next on a line of its own.
        if before.endswith('\\n"') and line[own] == '"':
            continue
        # A string literal that continues another ends its line, so that what follows it does not read as its text.
        if (before.lstrip().startswith('"') and line[own] != '"' and number > 2
                and comments[number - 3].rstrip().endswith('"')):
            continue
        # A string literal that continues one joins it as one literal, unless an escape that ends the first would take
        # in the characters that begin the second.
        joined = merged.get(number - 1, originals[number - 2].rstrip())
        if (before.endswith('"') and line[own] == '"' and not ESCAPE_END.search(before)
                and not RAW_STRING.search(before)):
            joined = joined[:-1] + line[own + 1:]
            joining = (starts[number - 2] + end - 1, starts[number - 1] + own + 1, "")
        else:
            tight = before.endswith(("(", "[")) or line[own] in ")],;"
            joined += ("" if tight else " ") + line[own:]
            joining = (starts[number - 2] + end, starts[number - 1] + own, "" if tight else " ")
        if within_limit(joined):
            merged[number] = joined
            problems.append((number, "wrap", "fits on the line before it", [joining]))

    collapsed = []
    joined_lines = set()    # the lines that a collapse joins, which another collapse in the same pass leaves alone
    for open_at, close_at in sorted(braces):
        if any(o < open_at < c for o, c in collapsed):
            continue
        first, last = line_of(text, open_at), line_of(text, close_at)
        if first == last:
            continue
        inner = text[open_at + 1:close_at]
        masked = code[open_at + 1:close_at]
        plain = (inner == commented[open_at + 1:close_at] and ";" not in masked and "\n#" not in "\n" + masked
                 and not any(number in raw for number in range(first + 1, last + 1)))
        if plain:
            joined = ""
            for piece in (part.strip() for part in inner.split("\n")):
                if not piece:
                    continue
                if joined and not joined.endswith(("(", "[", "{")) and not piece.startswith((")", "]", "}", ",")):
                    joined += " "
                joined += piece
            joined = joined[:-1] if joined.endswith(",") else joined
            whole = text[starts[first - 1]:open_at + 1] + joined + originals[last - 1][close_at - starts[last - 1]:]
            if len(whole.rstrip()) <= LINE_LIMIT and not joined_lines & {first, last}:
                collapsed.append((open_at, close_at))
                joined_lines.update(range(first, last + 1))
                problems.append((first, "initializer", "an initializer list that fits on one line",
                    [(open_at + 1, close_at, joined)]))
                continue
        edits = []
        rest = commented[open_at + 1:starts[first] - 1]
        if rest.strip():
            edits.append((open_at + 1, open_at + 1 + len(rest) - len(rest.lstrip()), "\n"))
        depth, commas, designated, item = 0, [], False, True
        for at in range(open_at + 1, close_at):
            character = code[at]
            if item and not character.isspace():
                designated = designated or DESIGNATED_ITEM.match(code, at) is not None
                item = False
            if character in "([{":
                depth += 1
            elif character in ")]}":
                depth -= 1
            elif character == "," and depth == 0:
                commas.append(at)
                item = True
        if designated:
            for comma in commas:
                after = commented[comma + 1:text.find("\n", comma)]
                if after.strip() and comma + 1 + len(after) < close_at:
                    edits.append((comma + 1, comma + 1 + len(after) - len(after.lstrip()), "\n"))
        # A macro may expand to items that end with their own comma, so a comma does not follow one that is last.
        end = len(commented[:close_at].rstrip())
        final = code[(commas[-1] + 1 if commas else open_at + 1):close_at]
        comma = "" if commented[end - 1] in ",{" or MACRO_CALL.fullmatch(final.strip()) else ","
        if commented[starts[last - 1]:close_at].strip():
            edits.append((end, close_at, comma + "\n"))
        elif comma:
            edits.append((end, end, comma))
        if edits:
            problems.append((first, "initializer", "an initializer list that wraps puts its items on lines of their own "
                "between its braces, each ending with a comma", edits))
    return problems


def check_indentation(report, path, text):
    """Code is indented four spaces a level, and never by tabs, as layout lays it out."""
    for number, line in enumerate(text.split("\n"), 1):
        own = len(line) - len(line.lstrip())
        if "\t" in line[:own]:
            report.add(path, number, "indentation", "indented with a tab, not spaces")
    for number, own, expected, _ in layout(text)[0]:
        if expected is not None and own != expected:
            report.add(path, number, "indentation", "begins at column %d, not %d" % (own + 1, expected + 1), LAYOUT)


def check_line_breaks(report, path, text):
    """A line reaches toward the column limit before it breaks, as layout_problems describes."""
    for number, check, message, _ in layout_problems(text):
        # The line-length check reports a line that runs too long.
        if check != "long":
            report.add(path, number, check, message, LAYOUT)


# What a conditional expression begins after: an opening bracket, the end of a block, a separator, or an assignment.
CONDITION_START = re.compile(r"[(\[{},;]|(?<![=!<>])=(?!=)")

# A keyword that an expression follows, which a conditional expression may begin after.
EXPRESSION_KEYWORD = re.compile(r"(?:return|co_return|throw)\b")


def conditional_spans(code):
    """Returns the spans, (start, end), of the conditional expressions in masked C or C++ `code`, outermost first. A
    conditional runs from the start of its condition to the end of its last operand."""
    spans = []
    for question in (m.start() for m in re.finditer(r"\?", code)):
        depth = 0
        start = 0
        for at in range(question - 1, -1, -1):
            character = code[at]
            if character in ")]":
                depth += 1
            elif character in "([{" and depth > 0:
                depth -= 1
            elif depth == 0 and CONDITION_START.match(code, at):
                start = at + 1
                break
            elif depth == 0 and not re.match(r"\w", code[at - 1:at]):
                keyword = EXPRESSION_KEYWORD.match(code, at)
                if keyword:
                    start = keyword.end()
                    break
        depth = 0
        pending = 1     # the colons that the conditionals from this one on still need
        end = len(code)
        for at in range(question + 1, len(code)):
            character = code[at]
            if character in "([{":
                depth += 1
            elif character in ")]}":
                if depth == 0:
                    end = at
                    break
                depth -= 1
            elif depth == 0 and character == "?":
                pending += 1
            elif depth == 0 and character == ":" and code[at - 1] != ":" and code[at + 1:at + 2] != ":":
                pending -= 1
            elif depth == 0 and character in ",;" and pending <= 0:
                end = at
                break
        spans.append((start, end))
    spans = sorted(set(spans))
    return [span for span in spans if not any(o[0] <= span[0] and span[1] <= o[1] and o != span for o in spans)]


def check_ternaries(report, path, text):
    """A conditional expression fits on one line. One that does not reads more easily as statements: an `if`, or a
    variable given its value in each branch."""
    code = mask_non_code(text)
    for start, end in conditional_spans(code):
        if "\n" in code[start:end].strip():
            report.add(path, line_of(text, start + len(code[start:end]) - len(code[start:end].lstrip())), "ternary",
                       "a conditional expression spans lines; fit it on one, or write it as statements")


def check_blank_lines(report, path, text):
    """Code is separated by at most one blank line."""
    for match in re.finditer(r"\n[ \t]*\n[ \t]*\n", text):
        report.add(path, line_of(text, match.start()) + 2, "blank-lines",
                   "two blank lines in a row")


def whole_line_comments(text):
    """Returns the 0-based numbers of the lines that are only a // comment, outside literals."""
    starts, offset = [], 0
    lines = text.split("\n")
    for line in lines:
        starts.append(offset)
        offset += len(line) + 1
    comments = [(start, end) for start, end, comment in c_literals(text) if comment and text.startswith("//", start)]
    found, at = set(), 0
    for number, start in enumerate(starts):
        first = start + len(lines[number]) - len(lines[number].lstrip())
        while at < len(comments) and comments[at][1] <= first:
            at += 1
        if at < len(comments) and comments[at][0] == first:
            found.add(number)
    return found


def check_comment_placement(report, path, text):
    """A comment covers the declarations below it, up to the next blank line. A comment that directly follows a
    declaration would read as part of the run above it, so outside function bodies a blank line separates them."""
    comments = whole_line_comments(text)
    lines = text.split("\n")
    code = mask_non_code(text).split("\n")
    scopes = []
    for number, line in enumerate(lines):
        if number in comments and number > 0 and "body" not in scopes and number - 1 not in comments:
            above = code[number - 1]
            indent = len(line) - len(line.lstrip())
            if above.rstrip().endswith(";") and indent <= len(above) - len(above.lstrip()):
                report.add(path, number + 1, "comment-placement",
                           "a comment covers the declarations below it up to the next blank line, so this one reads "
                           "as part of the run above. Put a blank line above it. If it is about only some of the "
                           "declarations below it, put a blank line after those too, or rewrite it to be true of the "
                           "whole run")
        for column, char in enumerate(code[number]):
            if char == "{":
                head = " ".join(code[max(0, number - 3):number]) + " " + code[number][:column]
                scope = re.search(r'\b(struct|enum|union|namespace|class)\b[^;()]*$|extern\s*$|=\s*$', head)
                scopes.append("scope" if scope or re.search(r'extern "C"\s*$', " ".join(
                    lines[max(0, number - 1):number]) + lines[number][:column]) else "body")
            elif char == "}" and scopes:
                scopes.pop()


def line_comments(text):
    """Returns the `//` comments of `text` by 0-based line number, as (column, whether code precedes it)."""
    starts = [0]
    for line in text.split("\n"):
        starts.append(starts[-1] + len(line) + 1)
    found, number = {}, 0
    for start, _, comment in c_literals(text):
        if not comment or not text.startswith("//", start):
            continue
        while starts[number + 1] <= start:
            number += 1
        column = start - starts[number]
        found[number] = (column, text[starts[number]:start].strip() != "")
    return found


def comment_words(line, column):
    """Returns the text of the comment at `column` without its marker, and whether it is indented past one space."""
    body = line[column + 2:]
    return body.strip(), body.startswith("  ")


# Matches a comment line whose text is a list item, which starts a line of its own.
LIST_ITEM = re.compile(r"^(?:[-*+]|\d+[.)])\s")

# Matches a line that links a spec, `shortname - url`, or is only a URL, which is a line of its own.
SPEC_LINE = re.compile(r"^(?:\S+ - )?https?://")


def check_comment_wrap(report, path, text):
    """A comment line breaks where it reaches the limit, so the next line's first word would not fit on it. A line
    indented past the comment's text, a list item and a row of aligned columns break where they are written."""
    lines = text.split("\n")
    comments = line_comments(text)
    for number, (column, _) in sorted(comments.items()):
        following = comments.get(number + 1)
        if following is None or following[0] != column or following[1]:
            continue
        current, _ = comment_words(lines[number], column)
        rest, indented = comment_words(lines[number + 1], column)
        if (not current or not rest or indented or LIST_ITEM.match(rest) or "  " in current or "  " in rest
                or SPEC_LINE.match(rest)
                or SECTION_RULE.match(lines[number]) or SUBSECTION.match(lines[number])
                or SUBSECTION.match(lines[number + 1])):
            continue
        if len(lines[number].rstrip()) + 1 + len(rest.split()[0]) <= LINE_LIMIT:
            report.add(path, number + 2, "comment-wrap",
                       "a comment line breaks where it reaches column %d; the first word of this line fits on the "
                       "line above" % LINE_LIMIT, REWRAP)


def check_trailing_comments(report, path, text):
    """A comment beside code continues on the lines below it, aligned with it. A comment line directly below it at
    another column would read as either its continuation or a comment on what follows, so a comment on what follows
    is set apart by a blank line."""
    comments = line_comments(text)
    for number, (column, beside) in sorted(comments.items()):
        if not beside:
            continue
        end = number
        while comments.get(end + 1) == (column, False):
            end += 1
        following = comments.get(end + 1)
        if following is not None and not following[1]:
            report.add(path, end + 2, "trailing-comment",
                       "a comment line below a comment beside code is aligned with it as its continuation, or set "
                       "apart by a blank line")


# Matches a comment's first phrase if it ends in a possessive with its noun left out: "a stroke's", "the round's, by
# node", "as PrKitNumber's".
LEANING = re.compile(r"^(?:(?:a|an|the|its|their|as|of)\s+)?[\w`.\- ]*?(?:'s|s')(?=\s*(?:$|[,;(]))")


def check_leaning_comments(report, path, text):
    """A comment beside a declaration says what the declaration holds in a phrase that stands on its own. A comment
    whose first phrase is a possessive with its noun left out leans on the name that it sits beside, which the reader
    must supply as the noun."""
    lines = text.split("\n")
    for number, (column, beside) in sorted(line_comments(text).items()):
        if not beside:
            continue
        body, _ = comment_words(lines[number], column)
        found = LEANING.match(body)
        # A clause may leave a possessive's noun to be read from earlier in the clause ("its margin collapses with its
        # first child's"), so only a phrase too short to have named the noun leans on the declaration.
        words = found.group(0).split() if found else []
        if found and len(words) <= 4 and words[0] != "and":
            report.add(path, number + 1, "leaning-comment",
                       "a comment beside a declaration leans on its name: \"%s\" leaves out the noun its possessive "
                       "names; say what the declaration holds" % body.split(",")[0])


# Matches lines in a run of declarations that declare nothing themselves: preprocessor conditions, the regions that
# the conventions wrap declarations in, scopes opening and closing, and lines that only import or check a name.
UNDECLARING = re.compile(
    r"^\s*(?:#\s*(?:if|ifdef|ifndef|elif|else|endif|error|pragma|include)\b"
    r"|PR_(?:ASSUME_NONNULL|NO_PADDING)_(?:BEGIN|END)\b"
    r"|(?:inline\s+)?namespace\b[^;]*\{|extern\s+\"C\"\s*\{|\}"
    r"|using\b|PR_STATIC_ASSERT\b|static_assert\b"
    r"|(?:struct|class)\s+\w+\s*;)")


def check_documented(report, path, text):
    """Every declaration in a header is under a comment. A comment covers the declarations below it up to the next
    blank line, so one comment documents a run of declarations."""
    code = mask_non_code(text).split("\n")
    lines = text.split("\n")
    comments = whole_line_comments(text)
    inside = set()      # the lines that a literal continues onto, whose blank lines do not end a run
    for start, end, comment in c_literals(text):
        if not comment:
            inside.update(range(line_of(text, start), line_of(text, end)))
    scopes = []         # each open brace: whether it opens a namespace or an extern "C" block
    run = None          # the lines of the current run at namespace scope
    runs = []
    for number, line in enumerate(lines):
        top = all(scopes)
        if top:
            if line.strip() == "" and number not in inside:
                if run:
                    runs.append(run)
                run = None
            else:
                run = (run or []) + [number]
        for column, char in enumerate(code[number]):
            if char == "{":
                head = " ".join(code[max(0, number - 3):number]) + " " + code[number][:column]
                scopes.append(re.search(r'\bnamespace\b[^;{}()]*$', head) is not None or re.search(
                    r'extern\s+"C"\s*$', " ".join(lines[max(0, number - 1):number]) + lines[number][:column])
                    is not None)
            elif char == "}" and scopes:
                scopes.pop()
    if run:
        runs.append(run)
    for run in runs:
        rest = [n for n in run if not (number_is_section(lines, n) or (n not in comments and UNDECLARING.match(
            lines[n])))]
        if rest and rest[0] not in comments:
            report.add(path, rest[0] + 1, "undocumented",
                       "a declaration in a header is under a comment, which may cover the run of declarations up to "
                       "the next blank line")


def number_is_section(lines, number):
    """Returns true if the line is a section's rule or name, or a subsection, which titles code without documenting
    it."""
    return (SECTION_RULE.match(lines[number]) is not None or SUBSECTION.match(lines[number]) is not None
            or (number > 0 and SECTION_RULE.match(lines[number - 1]) is not None))


# A section opens with a rule that reaches LINE_LIMIT and its name on the line below. A subsection is its name between
# three dashes on each side.
SECTION_RULE = re.compile(r"^([ \t]*)(//|#) ?-{3,}[ \t]*$")
SUBSECTION = re.compile(r"^[ \t]*(//|#) --- \S.*\S ---$")


def check_sections(report, path, text):
    """A section opens with a rule that reaches the line limit, then its name on the next line, and no rule below it. A
    subsection is one line, `// --- Name ---`."""
    lines = text.split("\n")
    closing = set()
    for number, line in enumerate(lines):
        if SUBSECTION.match(line) or number in closing:
            continue
        match = SECTION_RULE.match(line)
        if match is None:
            if re.match(r"^[ \t]*(//|#) ?-{2,}.*-{2,}[ \t]*$", line):
                report.add(path, number + 1, "section",
                           "a subsection is written `%s --- Name ---`, with one space inside each set of three "
                           "dashes" % match_marker(line))
            continue
        marker = match.group(2)
        expected = match.group(1) + marker + " " + "-" * (LINE_LIMIT - len(match.group(1)) - len(marker) - 1)
        name = lines[number + 1] if number + 1 < len(lines) else ""
        if line != expected:
            report.add(path, number + 1, "section",
                       "a section's rule is `%s ` and dashes out to column %d" % (marker, LINE_LIMIT))
        elif not re.match(r"^[ \t]*%s \S" % re.escape(marker), name) or SECTION_RULE.match(name):
            report.add(path, number + 1, "section",
                       "a section's rule is followed by its name, `%s Name`, on the next line. Name the section, "
                       "or remove the rule" % marker)
        elif number + 2 < len(lines) and SECTION_RULE.match(lines[number + 2]):
            closing.add(number + 2)
            report.add(path, number + 3, "section", "a section has a rule above its name only; remove this one")


def match_marker(line):
    return "#" if line.lstrip().startswith("#") else "//"


def check_allocation(report, path, text):
    """Reports ordinary new and delete, which need no include, so the header allowlist cannot catch them. The managed
    layer constructs and destroys in place, through pr/construct.h's placement form, and is exempt."""
    if is_managed_header(path):
        return
    code = mask_non_code(text)
    for match in re.finditer(r"^[ \t]*#[ \t]*include[^\n]*", code, re.M):
        directive = text[match.start():match.end()]
        if re.search(r'#\s*include\s*[<"]new[>"]', directive):
            report.add(path, line_of(text, match.start()), "allocation",
                       "<new> is forbidden; use pr/alloc.h")

    code = re.sub(r"^[ \t]*#[ \t]*include[^\n]*",
                  lambda m: " " * len(m.group(0)), code, flags=re.M)
    for match in re.finditer(r"\b(new|delete)\b", code):
        if match.group(0) == "delete" and re.search(r"=\s*$", code[max(0, match.start() - 64):match.start()]):
            continue  # A deleted function is not a deallocation expression.
        if path.endswith(".mm") and match.group(0) == "new" and re.match(r"\s*\]", code[match.end():]):
            continue  # [Class new] is an Objective-C message, which Objective-C's own reference counting owns.
        report.add(path, line_of(text, match.start()), "allocation",
                   "%s is forbidden; use alloc<T>/prMemoryFree" % match.group(0))


# The headers of core's managed layer, as they are included: types that construct, copy and destroy their contents,
# which applications and tests use. An implementation in lib/ manages memory explicitly, so it includes none of them.
MANAGED = {"pr/array.h", "pr/construct.h", "pr/defer.h", "pr/function.h", "pr/lock.h", "pr/map.h", "pr/print.h",
           "pr/set.h", "pr/string.h"}


def is_implementation(path):
    """Returns true for a file of a library's implementation: under lib, and not a test."""
    return posix(path).startswith(posix(os.path.join(ROOT, "lib")) + "/") and not is_test(path)


def is_managed_header(path):
    """Returns true for a header of the managed layer, which applications and tests use."""
    return any(posix(path).endswith("/lib/core/cpp/include/" + name) for name in MANAGED)


def check_destructors(report, path, text):
    """An implementation manages memory explicitly: an owner resets what it owns, and no type runs code when it goes
    away. So a file of lib declares no destructor, except a header of the managed layer."""
    if not is_implementation(path) or is_managed_header(path):
        return
    code = mask_non_code(text)
    for match in re.finditer(r"^[ \t]*(?:virtual[ \t]+)?(?:\w+::)?~[ \t]*(\w+)[ \t]*\([ \t]*\)", code, re.M):
        report.add(path, line_of(text, match.start(1)), "destructor",
                   "~%s is a destructor; an implementation resets what it owns explicitly" % match.group(1))


def check_managed_includes(report, path, text):
    """The managed layer is for applications and tests. A file of lib includes none of its headers, apart from the
    headers of the layer itself."""
    if not is_implementation(path) or is_managed_header(path):
        return
    for match in re.finditer(r'^[ \t]*#[ \t]*include[ \t]*"([^"]+)"', text, re.M):
        if match.group(1) in MANAGED:
            report.add(path, line_of(text, match.start()), "managed-include",
                       "%s is the managed layer's, which applications and tests use" % match.group(1))


ALIASES = ("u8", "u16", "u32", "u64", "i8", "i16", "i32", "i64", "f32", "f64",
           "usize", "isize")


def check_type_names(report, path, text):
    """Types use their standard spellings everywhere. A public C header cannot use an alias, so an alias in the
    implementation would give two names to every type that crosses the boundary."""
    for match in re.finditer(r"(?<![\w:.>])(%s)\b" % "|".join(ALIASES), mask_non_code(text)):
        report.add(path, line_of(text, match.start()), "type-name",
                   "%s is an alias; write the standard type" % match.group(1))


def enum_typedefs(text):
    """Returns the fixed-width typedefs that a file declares, which include the names of its enumerations."""
    return set(re.findall(r"^typedef \w+ (\w+);", text, re.M))


def check_enums(report, path, text, typedefs=None):
    """An enumeration whose values share a prefix is a type. A typedef names it right after the block, and its members
    are named for it: `X_A` for a type X, or `XFlag_A` for a set of flags XFlags or for flags that combine with the
    values of X in its own enumeration. A value made of other values of the set is a member of the set, not a separate
    constant. A cast of one of the set's own values to the set's type does nothing, wherever the type is declared.
    `typedefs` are those of every header, or the file's own if it is None. An arm of a conditional is the exception,
    because there the cast gives both arms the set's type."""
    # Another language's source in a string literal, such as a shader's, follows that language's rules.
    # An empty scoped enum of a fixed type is no set of values but an integer type of its own, which no other integer
    # converts to.
    # A named enumeration inside a class or a function breaks the rule as one at namespace scope does.
    for match in re.finditer(r"^[ \t]*enum\s+(?:class\s+)?\w+(?:\s*:\s*\w+)?\s*\{(\};)?", mask_non_code(text), re.M):
        if match.group(1) and "class" in match.group(0):
            continue
        report.add(path, line_of(text, match.start()), "enum-form",
                   "use an anonymous enum followed by a fixed-width typedef")
    for match in re.finditer(r"^enum(?: : \w+)? \{\n((?:    .*\n|\n)*?)\};\n(.*)$", text, re.M):
        names = re.findall(r"^    (\w+)", match.group(1), re.M)
        prefixes = {n.split("_", 1)[0] for n in names if "_" in n}
        if len(names) > 1 and len(prefixes) == 1 and not match.group(2).startswith("typedef"):
            report.add(path, line_of(text, match.start()), "enum-typedef",
                       "enum %s_ has no typedef naming its type" % prefixes.pop())
        typedef = re.match(r"typedef \w+ (\w+);", match.group(2))
        if typedef is None:
            continue
        name = typedef.group(1)
        allowed = (name + "_", name[:-1] + "_") if name.endswith("s") else (name + "_", name + "Flag_")
        for member in names:
            if not member.startswith(allowed):
                report.add(path, line_of(text, match.start()), "enum-member-name",
                           "%s is a member of %s, whose members start %s"
                           % (member, name, " or ".join(allowed)))
    for match in re.finditer(
            r"^(?:static\s+)?(?:const|constexpr)\s+\w+\s+(k\w+)\s*=\s*(\w+)_\w+\s*\|", text, re.M):
        report.add(path, line_of(text, match.start()), "enum-member",
                   "%s combines %s_ values; make it a %s_ member" % (match.group(1), match.group(2),
                                                                     match.group(2)))
    if typedefs is None:
        typedefs = enum_typedefs(text)
    code = mask_non_code(text)
    for match in re.finditer(r"\b(\w+)\((\w+)_\w+\)", code):
        arm = re.search(r"[?:]\s*$", code[:match.start()]) or re.match(r"\s*:", code[match.end():])
        if match.group(1) in typedefs and match.group(1).startswith(match.group(2)) and not arm:
            report.add(path, line_of(text, match.start()), "enum-cast",
                       "%s is already a %s" % (match.group(0), match.group(1)))


def check_cpp_form(report, path, text):
    """C++ is written as C++: `struct X {};` and `inline`, not the C spellings that the public headers need."""
    for match in re.finditer(r"^typedef struct\b|^static inline\b|\bNULL\b", mask_non_code(text), re.M):
        report.add(path, line_of(text, match.start()), "cpp-form",
                   "%s is the C spelling; write it as C++" % match.group(0))


def check_count_of(report, path, text):
    """A fixed-size array's count comes from countOf (pr/count_of.h). Dividing the sizes, or the standard
    library's spelling, would be a second way to say the same thing."""
    code = mask_non_code(text)
    pattern = (r"\bsizeof\s*\(?\s*([\w.:>-]+)\s*\)?\s*/\s*sizeof\s*\(?\s*(?:\*\s*\1|\1\s*\[\s*0\s*\])\s*\)?"
               r"|\bstd::size\s*\(")
    for match in re.finditer(pattern, code):
        report.add(path, line_of(text, match.start()), "count-of",
                   "%s is countOf's; use pr/count_of.h" % match.group(0).strip())


# A PrStringView of a string literal and its length: written as a temporary, or as a declaration's initializer.
LITERAL_VIEW = re.compile(r'\bPrStringView\s*(?:\w+\s*=\s*|\w+\s*)?[({]\s*"((?:[^"\\\n]|\\.)*)"\s*,\s*(\d+)\s*[)}]')


# A PrStringView made of a lone string literal, and the characters around it.
LONE_VIEW = re.compile(r'(\S?)\s*\bPrStringView\s*[({]\s*"(?:[^"\\\n]|\\.)*"\s*[)}]\s*(\S?)')


def check_literal_views(report, path, text):
    """A string literal converts to a PrStringView at compile time, so a view of a whole literal is the literal alone.
    Giving its length as well is a second way to say the same thing, and goes stale when the literal changes, and a
    literal converts where a view is expected without naming the type. A literal that holds a NUL needs its length,
    since the conversion stops at the NUL. An arm of a ternary names the type, since the other arm decides the
    conversion otherwise, and so does a view that is used in place, as a left operand or a range."""
    for match in LITERAL_VIEW.finditer(text):
        decoded = codecs.escape_decode(match.group(1).encode("utf-8"))[0]
        if b"\0" in decoded or len(decoded) != int(match.group(2)):
            continue
        report.add(path, line_of(text, match.start()), "literal-view",
                   'a view of a whole literal is the literal: write the literal where a view is expected, or '
                   'PrStringView{"%s"} where the type must be named' % match.group(1))
    for match in LONE_VIEW.finditer(text):
        before, after = match.group(1), match.group(2)
        if before in ("?", ":") or after not in (",", ")", ";", "}"):
            continue
        report.add(path, line_of(text, match.start() + len(before)), "literal-view",
                   "a literal converts to a view where one is expected; write the literal alone")


# A view built from the data() and size() of one object, such as `PrStringView{name.data(), name.size()}`: the view's
# type, and the object, a name with members and subscripts.
CONTAINER_VIEW = re.compile(
    r"\b(Pr(?:String|Byte)View)\s*[({]\s*([A-Za-z_]\w*(?:(?:\.|->)\w+|\[[^\]\n]*\])*)\.data\(\)\s*,\s*\2\.size\(\)"
    r"\s*[)}]")


def check_container_views(report, path, text):
    """A contiguous run with data() and size() converts to a view implicitly: a run of chars, such as std::string, to a
    PrStringView, and a run of bytes, such as std::vector<uint8_t>, to a PrByteView. Building the view from its data()
    and its size() spells out that conversion, and so does a helper that only returns such a view. Pass the object where
    a view is expected, or name the view's type around it where the type must be named."""
    for match in CONTAINER_VIEW.finditer(mask_non_code(text)):
        view, name = match.group(1), match.group(2)
        report.add(path, line_of(text, match.start()), "container-view",
                   "%s converts to a %s; pass it where a view is expected, or write %s(%s) where the type must be "
                   "named" % (name, view, view, name))


def enclosed_by_braces(code, at):
    """Returns true if the innermost bracket open around offset `at` is a braced initializer's brace, rather than a
    parenthesis, a subscript or a block's brace. A block's brace follows a parenthesis, a statement or a keyword."""
    depth = 0
    for i in range(at - 1, -1, -1):
        c = code[i]
        if c in ")]}":
            depth += 1
        elif c in "([{":
            if depth > 0:
                depth -= 1
                continue
            if c != "{":
                return False
            before = code[:i].rstrip()
            return not (before == "" or before[-1] in "){};" or re.search(r"\b(else|do|try)$", before))
    return False


# An enum's constants and the typedef that names its type: `enum { A, B }; typedef uint8_t T;`.
ENUM_WITH_TYPEDEF = re.compile(r"\benum\s*(?::\s*\w+\s*)?\{([^{}]*)\}\s*;\s*typedef\s+\w+\s+(\w+)\s*;", re.S)
ENUMERATOR = re.compile(r"(?:^|,)\s*([A-Za-z_]\w*)\s*(?==|,|$)")


def enum_constants(texts):
    """Returns each enum constant that a typedef names the type of, mapped to that typedef."""
    constants = {}
    for text in texts:
        for match in ENUM_WITH_TYPEDEF.finditer(mask_non_code(text)):
            for constant in ENUMERATOR.finditer(match.group(1)):
                constants[constant.group(1)] = match.group(2)
    return constants


CAST = re.compile(r"(?<![\w.>:])(?:static_cast\s*<\s*(\w+)\s*>|(\w+))\s*\(")


def cast_argument(code, open_at):
    """Returns the text between the parenthesis at `open_at` and the one that closes it, or None."""
    depth = 0
    for i in range(open_at, len(code)):
        if code[i] == "(":
            depth += 1
        elif code[i] == ")":
            depth -= 1
            if depth == 0:
                return code[open_at + 1:i]
    return None


def check_redundant_casts(report, path, text, constants):
    """A cast says that a value would not otherwise convert. A constant of an enum converts to the enum's type anywhere,
    except as a ternary's arm, whose other arm may make the ternary an int. A combination of flags by `|` converts to
    the flags' type wherever it is assigned, passed or returned, because the compiler knows that it fits, but a braced
    initializer rejects narrowing any value that is not a constant."""
    code = mask_non_code(text)
    for match in CAST.finditer(code):
        target = match.group(1) or match.group(2)
        if not target or not target[0].isupper():
            continue
        line = text[text.rfind("\n", 0, match.start()) + 1:match.start()]
        if line.lstrip().startswith("#"):
            continue
        argument = cast_argument(code, match.end() - 1)
        if argument is None:
            continue
        operands = [operand.strip() for operand in argument.split("|")]
        if len(operands) == 1:
            # A ternary's arm takes the cast, so that the other arm's type does not make the ternary an int.
            end = match.end() + len(argument) + 1
            before = code[:match.start()].rstrip()
            after = code[end:].lstrip()
            arm = before.endswith("?") or (before.endswith(":") and not before.endswith("::")) or after[:1] == ":"
            redundant = constants.get(operands[0]) == target and not arm
        else:
            simple = all(re.fullmatch(r"[A-Za-z_][\w.]*(?:->\w+)*|0", operand) for operand in operands)
            ours = any(constants.get(operand) == target for operand in operands)
            redundant = (target.endswith("Flags") and simple and ours
                         and not enclosed_by_braces(code, match.start()))
        if redundant:
            report.add(path, line_of(text, match.start()), "redundant-cast",
                       "%s(%s) converts without the cast" % (target, argument.strip()))


def check_auto(report, path, text):
    """A declaration names its type, so that the code says what a value is. `auto` stands only where there is no type
    to name: a lambda, a structured binding, a generic lambda's parameter, and a template parameter that is a value of
    any type."""
    code = mask_non_code(text)
    for match in re.finditer(r"\bauto\b", code):
        after = code[match.end():]
        if re.match(r"\s*\w+\s*=\s*\[", after) or re.match(r"\s*&{0,2}\s*\[", after):
            continue
        line_start = code.rfind("\n", 0, match.start()) + 1
        before = code[line_start:match.start()]
        template = re.match(r"\s*template\s*<", before)
        if template and ">" not in before[template.end():].replace("->", ""):
            continue
        if in_lambda_parameters(code, match.start()):
            continue
        report.add(path, line_of(text, match.start()), "auto", "a declaration names its type instead of auto")


def in_lambda_parameters(code, at):
    """Returns whether `at` is in the parameter list of a lambda."""
    depth = 0
    i = at - 1
    while i >= 0:
        c = code[i]
        if c == ")":
            depth += 1
        elif c == "(":
            if depth == 0:
                return re.search(r"\]\s*(?:<[^<>]*>\s*)?$", code[max(0, i - 200):i]) is not None
            depth -= 1
        elif c in ";{}":
            return False
        i -= 1
    return False


