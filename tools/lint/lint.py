def check_function_names(report, paths, texts):
    """A public function is named for its subject and what it does to it. A getter is named for what it returns, with
    no Get, except a Web IDL member, which keeps its interface's name. A lookup from another form is From<Source>, so
    `Of` and `Named` end no name: prLocaleFromTag, not prLocaleOf, and prFontFamilyFromName, not prFontFamilyNamed."""
    for path in paths:
        module = tag_module(path)
        text = texts[path]
        for match in SIGNATURE.finditer(mask_non_code(text)):
            name = match.group(1)
            if not name.startswith("pr") or name in FOREIGN_NAMES:
                continue
            words = re.findall(r"[A-Z][a-z0-9]*", name)
            if words[-1] in ("Of", "Named"):
                report.add(path, line_of(text, match.start(1)), "function-name",
                           "%s ends in %s: a lookup from another form is ...From<Source>, and a getter is named for "
                           "what it returns" % (name, words[-1]))
            elif "Get" in words and module not in WEB_IDL:
                report.add(path, line_of(text, match.start(1)), "function-name",
                           "%s has Get: a getter is named for what it returns" % name)


