# them in.
MARKDOWN_SPECS = {
    "commonmark": ("commonmark", os.path.join(ROOT, "third_party", "commonmark-spec", "spec.txt")),
    "gfm": ("cmark_gfm", os.path.join(ROOT, "third_party", "cmark-gfm", "test", "spec.txt")),
}


def markdown_spec_ids():
    """Returns the ids of the definitions and headings of each Markdown specification, by shortname. A definition is
    written `[term](@)`, and its id, like a heading's, is its text in lowercase with each run of spaces made a hyphen
    and any other character than a letter, a digit or a hyphen dropped."""
    def identifier(text):
        return re.sub(r"[^a-z0-9-]", "", re.sub(r"\s+", "-", text.strip().lower()))

    ids = {}
    for spec, (checkout, path) in MARKDOWN_SPECS.items():
        if not os.path.isfile(path):
            sys.exit("no %s specification at %s; run ./dev.sh fetch %s" % (spec, path, checkout))
        with open(path, encoding="utf-8") as f:
            text = f.read()
        terms = re.findall(r"\[([^\]\n]+)\]\(@\)", text)
        headings = re.findall(r"^#{1,6} +(.+)$", text, re.M)
        ids[spec] = {identifier(term) for term in terms + headings}
    return ids


def check_spec_references(report, path, text, ids):
    for match in SPEC_ID.finditer(text):
        spec, anchor = match.group(1), match.group(2)
        if spec not in ids:
            report.add(path, line_of(text, match.start()), "spec-reference",
                       "%s is not a spec webref extracts" % spec)
        elif anchor not in ids[spec]:
            report.add(path, line_of(text, match.start()), "spec-reference",
                       "%s has no passage #%s" % (spec, anchor))
    for match in SPEC_OTHER.finditer(text):
        if match.group(1) in ids:
            report.add(path, line_of(text, match.start()), "spec-reference",
                       "%s: name the passage by its id, as %s/#..."
                       % (" ".join(match.group(0).split()), match.group(1)))


