def check_dangling_names(report, path, text, defined):
    """A comment or a document that names a function, type or constant names one that the code has. A rename or a
    removal elsewhere leaves a reference that names nothing, which is drift between files that no compiler sees."""
    if os.path.basename(path) in ILLUSTRATING_DOCS:
        return
    spans = ([(m.start(), m.end()) for m in COMMENT.finditer(text)]
             if not path.endswith(".md") else [(m.start(), m.end()) for m in re.finditer(r"`[^`\n]+`", text)])
