def check_pragma_once(report, path, text):
    if "#pragma once" not in text:
        report.add(path, 1, "pragma-once", "header has no #pragma once")


def check_nullability_region(report, path, text):
    """A header wraps what it declares in an assume-nonnull region, outside the scope that it declares into. Clang's
    -Wnullability-completeness warns only once a file annotates something, so nothing else checks a header that omits
    the region."""
    if not declares_anything(text):
        return

    begin = text.find("PR_ASSUME_NONNULL_BEGIN")
    end = text.rfind("PR_ASSUME_NONNULL_END")
    if begin < 0 or end < 0:
        report.add(path, 1, "nullability", "header declares nothing in an assume-nonnull region")
        return

    for scope in ('extern "C" {', "namespace pr_impl {", "namespace pr {"):
        opened = text.find(scope)
        if opened < 0:
            continue
        if begin > opened:
            report.add(path, line_of(text, begin), "nullability",
                       "assume-nonnull begins inside %s, not around it" % scope.rstrip(" {"))
        closed = text.rfind("}", 0, text.rfind("PR_ASSUME_NONNULL_END"))
        if end < closed:
            report.add(path, line_of(text, end), "nullability",
                       "assume-nonnull ends before the end of %s" % scope.rstrip(" {"))
        break


def check_public_includes(report, path, text):
    """A public header never includes an implementation header."""
    for match in re.finditer(r'#include "([^"]+)"', text):
        included = match.group(1)
        if "/src/" in included:
            report.add(path, line_of(text, match.start()), "public-include",
                       "public header includes the implementation header %s" % included)


def declares_anything(text):
    """Returns true if a file has code, not just preprocessor lines. A header of only macros has no names to put in a
    namespace."""
    for line in text.split("\n"):
        line = line.strip()
        if not line or line.startswith(("#", "//", "/*", "*")):
            continue
        return True
    return False


def namespace_spans(code, name):
    """Returns the spans of code inside each `namespace <name> {` block."""
    spans = []
    for match in re.finditer(r"^namespace %s \{" % name, code, re.M):
        depth = 0
        for brace in re.finditer(r"\{|\}", code[match.end() - 1:]):
            depth += 1 if brace.group(0) == "{" else -1
            if depth == 0:
                spans.append((match.end(), match.end() - 1 + brace.start()))
                break
    return spans


def check_namespace(report, path, text, implements_public, name):
    """Implementation lives in pr_impl, and the C++ API in pr. The C API is in neither. A public header declares names
    with C linkage, and the source that implements it defines them at global scope, beside a pr_impl block for any
    internal functions that it also defines. A header that holds only C opaque types declares nothing internal. `name`
    is the namespace of the file: pr for a header of the C++ API and the source that implements it, and pr_impl for the
    rest."""
    internal = "\n".join(line for line in text.split("\n")
                         if not OPAQUE_TYPE.match(line.strip()) and not line.startswith("PR_ASSUME_NONNULL_"))
    if not declares_anything(internal):
        return
    public = is_public(path) or implements_public
    code = mask_non_code(text)
    spans = namespace_spans(code, "pr_impl")
    if public:
        for match in SIGNATURE.finditer(code):
            if re.match(r"pr[A-Z]", match.group(1)) and any(a <= match.start() < b for a, b in spans):
                report.add(path, line_of(text, match.start()), "namespace",
                           "public API %s is inside pr_impl" % match.group(1))
        return
    if not namespace_spans(code, name):
        report.add(path, 1, "namespace", "file is not inside %s" % name)
    other = "pr_impl" if name == "pr" else "pr"
    for match in re.finditer(r"^namespace %s \{" % other, code, re.M):
        report.add(path, line_of(text, match.start()), "namespace",
                   "the C++ API is in pr and its implementation in pr_impl; this file's namespace is %s" % name)


QUALIFIED = re.compile(r"(?<![\w:])(?:::)?pr(?:_impl)?::")

# Matches a C opaque type: the public handle, at global scope, derived from the internal type that it names.
OPAQUE_TYPE = re.compile(r"^struct Pr\w+ : (?:pr_impl::)?\w+ \{\};$")


# The head of an explicit specialization.
EXPLICIT_SPECIALIZATION = re.compile(r"\btemplate\s*<\s*>")


def specialization_lines(code):
    """Returns the numbers of the lines of masked `code` that are within an explicit specialization: from its
    `template <>` to the brace that closes its body, or to the semicolon that ends a specialization with none."""
    lines = set()
    for match in EXPLICIT_SPECIALIZATION.finditer(code):
        depth = 0
        end = len(code)
        for at in range(match.end(), len(code)):
            character = code[at]
            if character == "{":
                depth += 1
            elif character == "}":
                depth -= 1
                if depth == 0:
                    end = at
                    break
            elif character == ";" and depth == 0:
                end = at
                break
        lines.update(range(line_of(code, match.start()), line_of(code, end) + 1))
    return lines


def check_qualified(report, path, text):
    """Only a macro spells out `pr::` or `pr_impl::`, because it expands in its caller's scope. Code imports the
    namespace with a using-directive: `using namespace pr;` in an application, and `using namespace pr_impl;` in the
    library. A header names the base of each C opaque type that it declares. An explicit specialization of another
    library's template names the pr types that it is for with `pr::`, since it is written in that library's
    namespace."""
    masked = mask_non_code(text)
    code = masked.split("\n")
    raw = text.split("\n")
    specializing = specialization_lines(masked)
    in_macro = False
    for index, line in enumerate(code):
        macro = in_macro or line.lstrip().startswith("#")
        in_macro = macro and raw[index].rstrip().endswith("\\")
        if macro or not QUALIFIED.search(line):
            continue
        if path.endswith(".h") and OPAQUE_TYPE.match(line):
            continue
        if index + 1 in specializing and all(m.group(0).lstrip(":") == "pr::" for m in QUALIFIED.finditer(line)):
            continue
        report.add(path, index + 1, "qualified",
                   "%s outside a macro; take the namespace with a using-directive"
                   % QUALIFIED.search(line).group(0).lstrip(":"))


def check_application_namespace(report, path, text):
    """An application uses the C++ API, namespace pr, and never the implementation's namespace, pr_impl, which only
    the library's own code names."""
    for match in re.finditer(r"\bpr_impl\b", mask_non_code(text)):
        report.add(path, line_of(text, match.start()), "application-namespace",
                   "an application uses namespace pr, not the implementation's pr_impl")


