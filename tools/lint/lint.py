INCLUDE = re.compile(r'^\s*#\s*include\s*([<"])([^>"]+)[>"]')
DIRECTIVE = re.compile(r"^\s*#\s*(?:if|ifdef|ifndef|elif|else|endif|define|undef)\b")
INCLUDE_SECTIONS = ("the file's own header", "public headers", "internal headers",
                    "third-party headers", "system headers")


def own_headers(path, names):
    """Returns the headers that a source implements, as it includes them: its public header, then the header with its
    own name beside it."""
    relative = os.path.relpath(path, ROOT).replace(os.sep, "/")
    if not relative.endswith((".cpp", ".c", ".mm")):
        return []
    stem = os.path.splitext(os.path.basename(relative))[0]
    directory = os.path.dirname(relative)
    beside = (directory[len("lib/"):] if relative.startswith("lib/") else directory) + "/" + stem + ".h"
    public = [n for n in names if n.startswith("pr/") and os.path.basename(n) == stem + ".h"
              and os.path.dirname(relative).endswith("/src")]
    return public + [n for n in names if n == beside]


def include_section(name, bracket, own):
    """Returns the section that an include belongs to: 0 to 4, as INCLUDE_SECTIONS names them."""
    if name in own:
        return 0
    if bracket == "<":
        return 4
    if name in THIRD_PARTY:
        return 3
    return 1 if name.startswith("pr/") else 2


def check_include_order(report, path, text):
    """Includes form up to five sections, in this order: the file's own header, public headers, internal headers,
    third-party headers, and system headers. The sections are one blank line apart, each sorted, and all quoted except
    the system headers. A directive between two includes, such as a conditional around one, separates them, and
    neither the section checks nor the sort check reads across it. A third-party header is included only where
    THIRD_PARTY allows."""
    relative = os.path.relpath(path, ROOT).replace(os.sep, "/")
    lines = text.split("\n")
    entries = []
    for number, line in enumerate(lines, 1):
        match = INCLUDE.match(line)
        if match:
            entries.append((number, match.group(1), match.group(2).strip()))
    own = own_headers(path, [name for _, _, name in entries])
    sections = []
    for number, bracket, name in entries:
        section = include_section(name, bracket, own)
        sections.append(section)
        if name in THIRD_PARTY:
            if bracket == "<":
                report.add(path, number, "include-order", "%s needs quotes" % name)
            if not any(fnmatch.fnmatchcase(relative, place) for place in THIRD_PARTY[name]):
                report.add(path, number, "include-order", "%s is not included here" % name)
        elif section == 4 and name.startswith("pr/"):
            report.add(path, number, "include-order", "%s needs quotes" % name)
    for (a, b) in zip(range(len(entries)), range(1, len(entries))):
        number, bracket, name = entries[a]
        next_number, next_bracket, next_name = entries[b]
        spanned = lines[number:next_number - 1]
        if any(DIRECTIVE.match(line) for line in spanned):
            continue
        if any(line.strip() for line in spanned):
            report.add(path, number + 1, "include-order", "text between includes")
            continue
        section, next_section = sections[a], sections[b]
        if len(spanned) > 1:
            report.add(path, next_number, "include-order",
                       "more than one blank line before %s" % next_name)
        elif spanned and next_section <= section:
            report.add(path, next_number, "include-order", "%s belongs with %s"
                       % (next_name, INCLUDE_SECTIONS[section]))
        elif not spanned and next_section != section:
            report.add(path, next_number, "include-order", "%s needs a blank line between %s and %s"
                       % (next_name, INCLUDE_SECTIONS[section], INCLUDE_SECTIONS[next_section]))
        elif not spanned and section == 0:
            if own.index(next_name) < own.index(name):
                report.add(path, next_number, "include-order",
                           "%s belongs before %s" % (next_name, name))
        elif not spanned and include_sort_key(next_name, next_bracket) <= include_sort_key(
                name, bracket):
            report.add(path, next_number, "include-order",
                       "%s is out of order after %s" % (next_name, name))


def include_sort_key(name, bracket):
    """Returns the sort key of an include: the path with its closing delimiter, so <string.h> sorts before <string>.
    <windows.h> sorts first, since the other headers of the Windows SDK need its declarations."""
    if bracket == "<" and name == "windows.h":
        return ""
    return name + (">" if bracket == "<" else '"')


def declarations(text):
    """Returns the function names declared at namespace scope, in order."""
    return [m.group(1) for m in SIGNATURE.finditer(text) if m.group(2) == ";"]


def definitions(text):
    """Returns the function names defined at namespace scope, in order, skipping file-local helpers."""
    names = []
    for match in SIGNATURE.finditer(text):
        if match.group(2) != "{":
            continue
        if match.group(0).lstrip().startswith("static"):
            continue
        names.append(match.group(1))
    return names


def check_defined(report, headers, sources, texts):
    """Every function that a header declares is defined, so the header promises nothing that a caller cannot link
    against. An inline function may be defined later in a header. A name with no capital, such as strlen, belongs to
    the platform, as does a compiler's intrinsic, whose name starts with an underscore."""
    defined = set()
    for path in sources + headers:
        defined.update(definitions(texts[path]))
    for path in headers:
        for match in SIGNATURE.finditer(texts[path]):
            if (match.group(2) == ";" and match.group(1) not in defined
                    and match.group(1) != match.group(1).lower() and not match.group(1).startswith("_")
                    and not match.group(0).startswith("typedef")
                    and re.search(r"\b%s\s*\(" % match.group(1), match.group(0))
                    and not re.search(r"\(\s*\*", match.group(0))):
                report.add(path, line_of(texts[path], match.start()), "undefined",
                           "%s is declared and never defined" % match.group(1))


# A type's lifetime follows one of two vocabularies. Either its caller destroys it (Create/Destroy),
# or its holders share it (Create/Retain/Release). The name says which.
LIFETIME = re.compile(r"\b([a-z]+[A-Z]\w*?)(Destroy|Retain|Release|Free|Ref|Unref|AddRef|Dispose)\s*\(")


def check_lifetime(report, paths, texts):
    """The lifetime functions that the headers declare for each type are Destroy alone, or Retain and Release
    together. A function is one of a type's if its first parameter is a pointer to the type that it names, so freeing
    raw memory (prMemoryFree) is not."""
    verbs = {}
    for path in paths:
        for match in LIFETIME.finditer(texts[path]):
            if SIGNATURE.match(texts[path], texts[path].rfind("\n", 0, match.start()) + 1) is None:
                continue
            name = match.group(1)
            first = texts[path][match.end():].split(",")[0].split(")")[0]
            if not re.search(r"\b%s%s\s*\*" % (name[0].upper(), re.escape(name[1:])), first):
                continue
            verbs.setdefault(match.group(1),
                             []).append((match.group(2), path, line_of(texts[path], match.start())))
    for name, found in sorted(verbs.items()):
        kinds = {verb for verb, _, _ in found}
        for verb, path, line in found:
            if verb not in ("Destroy", "Retain", "Release"):
                problem = ("%s%s is no lifetime function: a type has Destroy, or Retain and Release"
                           % (name, verb))
            elif verb != "Destroy" and "Destroy" in kinds:
                problem = ("%s has Destroy and %s: a type has Destroy, or Retain and Release"
                           % (name, verb))
            elif verb != "Destroy" and not {"Retain", "Release"} <= kinds:
                problem = "%s has %s alone: Retain and Release come together" % (name, verb)
            else:
                continue
            report.add(path, line, "lifetime", problem)


# Matches the functions that make or end a handle, which name the handle: pr<Handle>Create..., Destroy, Retain,
# Release, Begin and End.
HANDLE_LIFETIME = re.compile(r"\bpr([A-Z]\w*?)(Create\w*|Destroy|Retain|Release|Begin|End)\s*\(")

def public_module(path):
    """Returns the module that a public header belongs to: the directory that holds its include tree."""
    return posix(path).split("/include/")[0]


# Matches a record of functions, which a backend's state starts with. Its first member destroys the backend.
RECORD = re.compile(r"^struct Pr(\w+) \{\s*void \(\*(?:PR_NULLABLE )?destroyFn\)\(Pr(\w+)\*", re.M)


def public_handles(paths, texts):
    """Returns the handles of the public headers, by name without the Pr prefix, each with its module: the types with
    lifetime functions, and the records of functions that backends start with."""
    handles = {}
    for path in paths:
        code = mask_non_code(texts[path])
        for match in HANDLE_LIFETIME.finditer(code):
            handles.setdefault(match.group(1), public_module(path))
        for match in RECORD.finditer(code):
            if match.group(1) == match.group(2):
                handles.setdefault(match.group(1), public_module(path))
    return handles


def check_backend_names(report, paths, texts):
    """An interface's record is named for what callers hold, never `Backend`. A backend's own header declares the
    function that makes the record, pr<Interface><Backend>Create, named for the backend's directory,
    lib/<interface>/backends/<backend> or lib/<interface>/comparisons/<backend>."""
    handles = public_handles(paths, texts)
    for path in paths:
        text = texts[path]
        code = mask_non_code(text)
        for match in re.finditer(r"\btypedef struct (Pr\w*Backend)\b", code):
            report.add(path, line_of(text, match.start()), "backend-name",
                       "%s is named for its role, not Backend" % match.group(1))
        backend = backend_of(path)
        if backend is None:
            continue
        for match in MAKES.finditer(code):
            name = match.group(2)
            made = [match.group(1)] if match.group(1) else []
            made += [m.group(1) for m in OUT_HANDLE.finditer(match.group(3))]
            for made_type in made:
                if handles.get(made_type) not in interfaces_of(backend):
                    continue
                expected = "pr" + backend_file_prefix(backend).replace("_", "") + "create"
                if name.lower() != expected:
                    report.add(path, line_of(text, match.start()), "backend-name",
                               "%s makes a Pr%s, so it is named like %s" % (name, made_type, expected))


# The libraries that may include each other's implementation headers: the web engine's, for now.
SHARED_IMPLEMENTATION = ("lib/css/", "lib/dom/", "lib/html/", "lib/mathml/", "lib/svg/", "lib/xhr/")


def check_private_includes(report, path, text):
    """A library reaches another through its public headers, never through its implementation (`<module>/src/`) or its
    tests (`<module>/tests/`). Its own tests, bindings and backends sit inside it, and the libraries under
    SHARED_IMPLEMENTATION share their implementations. A backend reaches what its interface's backends share
    (lib/<interface>/backends/shared)."""
    relative = os.path.relpath(path, ROOT).replace(os.sep, "/")
    for match in re.finditer(r'^#include "((?:[\w]+/)+?)src/[^"]+"', text, re.M):
        module = "lib/" + match.group(1)
        if relative.startswith(module):
            continue
        shared = re.match(r"lib/(\w+)/backends/shared/$", module)
        if shared is not None and re.match(r"lib/%s/(?:backends|comparisons)/" % shared.group(1), relative):
            continue
        if relative.startswith(SHARED_IMPLEMENTATION) and module.startswith(SHARED_IMPLEMENTATION):
            continue
        report.add(path, line_of(text, match.start()), "private-include",
                   "%s reaches into %s's implementation; include its public headers" % (relative, module[:-1]))
    # A module's tests are as private as its implementation, with no library that shares them.
    for match in re.finditer(r'^#include "((?:[\w]+/)+?)tests/[^"]+"', text, re.M):
        module = "lib/" + match.group(1)
        if not relative.startswith(module):
            report.add(path, line_of(text, match.start()), "private-include",
                       "%s reaches into %s's tests; what they share with others belongs in tools" % (relative,
                                                                                                     module[:-1]))


def binding_layer(path):
    """Returns the QuickJS layer that a file belongs to, as <module>/quickjs/ or <module>/quickjs_cpp/ in include form,
    or None."""
    match = re.search(r"(?:^|/)lib/((?:\w+/)+?quickjs(?:_cpp)?/)", posix(path))
    return match.group(1) if match is not None else None


def check_binding_includes(report, path, text):
    """A binding reaches every module through its public API, its own module's too. It includes public headers, which
    include the language layers of core and of other modules, and its own layer's implementation, never a module's
    implementation."""
    layer = binding_layer(path)
    for match in re.finditer(r'^#include "([^"]+)"', text, re.M):
        header = match.group(1)
        if not (header.startswith("pr/") or header.startswith(layer) or header == "quickjs.h"
                or header == "tools/harness/test.h"):
            report.add(path, line_of(text, match.start()), "binding-include",
                       "a binding includes %s, which is not public API" % header)


def backend_of(path):
    """Returns the backend that a file belongs to, as lib/<interface>/backends/<backend>, or the comparison, as
    lib/<interface>/comparisons/<name>, or None. A comparison follows a backend's rules."""
    parts = os.path.relpath(path, ROOT).replace(os.sep, "/").split("/")
    if len(parts) > 4 and parts[0] == "lib" and parts[2] in ("backends", "comparisons"):
        return "/".join(parts[:4])
    return None


def backend_file_prefix(backend):
    """Returns the prefix of a backend's file names, <interface>_<backend>."""
    parts = backend.split("/")
    return parts[1] + "_" + parts[3]


def interfaces_of(backend):
    """Returns the modules that a backend may implement, as absolute paths: its interface, and a backend of that
    interface whose name its name extends, as fragment_metal extends fragment."""
    parts = backend.split("/")
    words = parts[3].split("_")
    found = [os.path.join(ROOT, "lib", parts[1])]
    found += [os.path.join(ROOT, "lib", parts[1], "backends", "_".join(words[:i])) for i in range(1, len(words))]
    return [posix(module) for module in found]


# Patterns for a declaration that makes a handle. MAKES matches the declaration, which returns a pointer to the handle
# or writes one through `out`, and OUT_HANDLE matches an `out` parameter of a handle.
MAKES = re.compile(r"^(?!\s)(?!typedef)(?:const\s+)?(?:Pr(\w+)\s*\*\s*(?:PR_NULLABLE\s+)?)?[\w ]*?\b(pr[A-Z]\w*)\("
                   r"([^;{]*?)\)\s*;", re.M)
OUT_HANDLE = re.compile(r"(?:const\s+)?Pr(\w+)\s*\*\s*PR_NULLABLE\s*\*\s*PR_NONNULL\s+out\b")


def check_creators(report, paths, texts):
    """A handle that its caller destroys is made by its Create or Begin function, because every lifetime function is
    named for the handle that it makes or ends. A function named Create makes the handle that it is named for, and
    every opaque type is a handle here, so a member that makes one is the handle's Create, as Document's createElement
    is prDomElementCreate. A record of functions is instead made by its backends' constructors, whose names extend the
    record's, as prStorageDiskCreate makes a PrStorage.

    A handle with Destroy is made by Create, used any number of times, and destroyed, so that an operation that
    produces one fills a handle that its caller made and can reuse, rather than making a new one for each call."""
    opaque = set(public_handles(paths, texts))
    for path in paths:
        opaque.update(re.findall(r"^typedef struct Pr(\w+) Pr\1;", mask_non_code(texts[path]), re.M))
    records = set()
    for path in paths:
        records.update(m.group(1) for m in RECORD.finditer(mask_non_code(texts[path])) if m.group(1) == m.group(2))
    made = {}
    for path in paths:
        code = mask_non_code(texts[path])
        for match in MAKES.finditer(code):
            name, parameters = match.group(2), match.group(3)
            types = [match.group(1)] if match.group(1) else []
            types += [m.group(1) for m in OUT_HANDLE.finditer(parameters)]
            for made_type in types:
                made.setdefault(made_type, set()).add(name)
                creator = re.match(r"pr(\w+?)(Create|Begin)", name)
                if (creator is not None and not creator.group(1).startswith(made_type) and made_type in opaque
                        and made_type not in records and not backend_of(path)):
                    report.add(path, line_of(texts[path], match.start()), "creator",
                               "%s makes a Pr%s, so it is named pr%s%s..." % (name, made_type, made_type,
                                                                             creator.group(2)))
        for match in re.finditer(r"^void\s+pr(\w+)Destroy\(", code, re.M):
            handle = match.group(1)
            if handle in records:
                continue
            if not any(re.match(r"pr%s(Create|Begin)" % handle, f) for f in made.get(handle, ())):
                if not re.search(r"\bpr%s(Create|Begin)\w*\(" % handle, "\n".join(texts[p] for p in paths)):
                    report.add(path, line_of(texts[path], match.start()), "creator",
                               "Pr%s has Destroy but no Create or Begin that makes it: an operation that "
                               "produces one fills a Pr%s that its caller made and reuses" % (handle, handle))


def check_shared_includes(report, path, text):
    """What an interface's backends share, lib/<interface>/backends/shared, is theirs alone: only the backends and
    comparisons of that interface include its headers (pr/<interface>_shared_*.h). Clients see the interface."""
    relative = os.path.relpath(path, ROOT).replace(os.sep, "/")
    for match in re.finditer(r'^#include "pr/((\w+?)_shared(?:_\w+)?)\.h"', text, re.M):
        interface = match.group(2)
        if not re.match(r"lib/%s/(?:backends|comparisons)/" % re.escape(interface), relative):
            report.add(path, line_of(text, match.start()), "shared-include",
                       "pr/%s.h is shared by the backends of lib/%s, and only they include it"
                       % (match.group(1), interface))


def check_backend_includes(report, path, text):
    """A backend reaches its interface, and every other module, through the public API. It includes public headers,
    which include core's C++ layer, never another module's implementation, except what its interface's backends share
    (lib/<interface>/backends/shared). A backend's tests also reach what its interface's tests share with them
    (lib/<interface>/tests), as the interface's own tests run on every backend."""
    own = backend_of(path)[len("lib/"):] + "/"
    interface = own.split("/")[0]
    allowed = ("pr/", own, interface + "/backends/shared/")
    if "/tests/" in os.path.relpath(path, ROOT).replace(os.sep, "/"):
        allowed += (interface + "/tests/",)
    for match in re.finditer(r'^#include "([^"]+)"', text, re.M):
        header = match.group(1)
        if not (header.startswith(allowed) or header in THIRD_PARTY):
            report.add(path, line_of(text, match.start()), "backend-include",
                       "a backend includes %s, which is not public API" % header)


