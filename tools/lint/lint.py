def check_builtins(report, path, text):
    """A compiler's builtin is reached through the core header that wraps it, such as pr/float.h for the C library's
    arithmetic, so that the library works with a compiler that spells it otherwise or lacks it. A type intrinsic, such
    as __is_trivially_copyable, is reached through pr/type_traits.h."""
    relative = os.path.relpath(path, ROOT).replace(os.sep, "/")
    code = mask_non_code(text)
    if relative not in BUILTINS:
        for match in re.finditer(r"\b__builtin_\w+", code):
            report.add(path, line_of(text, match.start()), "builtin",
                       "%s belongs behind a core header, such as pr/float.h" % match.group(0))
    if relative != TYPE_TRAITS:
        for match in re.finditer(r"\b__is_\w+(?=\s*\()", code):
            report.add(path, line_of(text, match.start()), "builtin",
                       "%s belongs behind pr/type_traits.h" % match.group(0))


def check_stdlib(report, path, text):
    """Only the three headers that the C API needs are used directly. Everything else goes behind a core header, so the
    library's use of the standard library stays in one place. The tests and the harness headers that they include are
    held to it as the library is: there are many tests, and a standard header such as <string> or <vector> costs more to
    compile than most tests do."""
    allowed = {"stdbool.h", "stddef.h", "stdint.h"}
    relative = os.path.relpath(path, ROOT).replace(os.sep, "/")
    # A public header is included by every client of its library, so it wraps nothing: whatever it included would be
    # included everywhere. What it needs of a platform it declares itself.
    if "/include/" in relative and relative in WRAPPERS:
        report.add(path, 1, "stdlib", "a public header cannot wrap a system facility; declare what it needs")
    else:
        allowed |= WRAPPERS.get(relative, set())
    for match in re.finditer(r"#include <([^>]+)>", mask_non_code(text)):
        name = match.group(1)
        if name in allowed:
            continue
        report.add(path, line_of(text, match.start()), "stdlib",
                   "<%s> should be behind a core header" % name)


NON_CODE = re.compile(
    r'//[^\n]*|/\*[\s\S]*?\*/'
    r'|(?:u8|u|U|L)?R"(?P<delimiter>[^ ()\\\t\r\n]{0,16})\([\s\S]*?\)(?P=delimiter)"'
    r'|"(?:\\[\s\S]|[^"\\])*"|\'(?:\\[\s\S]|[^\'\\])*\'')


def blank(value):
    """Returns `value` with every character but its line breaks replaced by a space."""
    return "\n".join(" " * len(line) for line in value.split("\n"))


# Many checks read the same text, so the masks and literals of each text are found once.
@functools.cache
def mask_non_code(text):
    """Returns the text with its comments and literals hidden, without changing diagnostic offsets or line numbers."""
    return NON_CODE.sub(lambda match: blank(match.group(0)), text)


def mask_raw_strings(text):
    """Returns the text with the contents of its raw string literals hidden, which are text such as samples of other
    languages rather than code, without changing diagnostic offsets or line numbers."""
    def mask(match):
        value = match.group(0)
        return value if not RAW_STRING.match(value) else blank(value)
    return NON_CODE.sub(mask, text)


RAW_STRING = re.compile(r'(?:u8|u|U|L)?R"')


# The last column that a line may reach. Comments are wrapped to it.
LINE_LIMIT = 120

# The most that a line of code may run past LINE_LIMIT with: a short tail reads better at the end of the line than alone
# on the next.
SHORT_TAIL = 10


def within_limit(line):
    """Returns true if a line of code ends by LINE_LIMIT, or runs past it only with a short tail: what follows its last
    space before the limit."""
    if len(line) <= LINE_LIMIT:
        return True
    return len(line) <= LINE_LIMIT + SHORT_TAIL and len(line) - line.rfind(" ", 0, LINE_LIMIT + 1) - 1 <= SHORT_TAIL


@functools.cache
def c_literals(text):
    """Returns the comments and literals of C or C++ `text`, as (start, end, comment)."""
    return tuple((m.start(), m.end(), m.group(0).startswith(("//", "/*")))
                 for m in NON_CODE.finditer(text))


def python_literals(text):
    """Returns the comments and strings of Python `text`, as (start, end, comment). An f-string counts as one string,
    and a docstring, which is prose, counts as a comment."""
    docstrings = set()
    for node in ast.walk(ast.parse(text)):
        body = getattr(node, "body", None)
        if (isinstance(node, (ast.Module, ast.ClassDef, ast.FunctionDef, ast.AsyncFunctionDef))
                and body and isinstance(body[0], ast.Expr)
                and isinstance(body[0].value, ast.Constant)
                and isinstance(body[0].value.value, str)):
            docstrings.add((body[0].lineno, body[0].col_offset))
    starts = [0]
    for line in text.split("\n"):
        starts.append(starts[-1] + len(line) + 1)
    offset = lambda position: starts[position[0] - 1] + position[1]
    literals = []
    opened = None
    for token in tokenize.generate_tokens(io.StringIO(text).readline):
        if token.type == tokenize.FSTRING_START:
            opened = opened if opened is not None else offset(token.start)
        elif token.type == tokenize.FSTRING_END:
            literals.append((opened, offset(token.end), False))
            opened = None
        elif opened is None and token.type in (tokenize.STRING, tokenize.COMMENT):
            prose = token.type == tokenize.COMMENT or token.start in docstrings
            literals.append((offset(token.start), offset(token.end), prose))
    return literals


def check_line_length(report, path, text, literals=None):
    """A line ends by LINE_LIMIT, except for text that cannot break there: a string literal that runs past the limit,
    followed only by what closes the expression, or a comment that is one word, as a spec reference can be. `literals`
    are the comments and literals of `text`, as (start, end, comment). If it is None, the text is prose, which may run
    past the limit only with its last word, such as a URL. Rows of tables in prose may also run past it."""
    start = 0
    for number, line in enumerate(text.split("\n"), 1):
        end = start + len(line)
        if len(line) > LINE_LIMIT and literals is None:
            tail = line[line.rfind(" ", 0, LINE_LIMIT) + 1:]
            if not line.lstrip().startswith("|") and " " in tail:
                report.add(path, number, "line-length",
                           "line is %d columns, past %d" % (len(line), LINE_LIMIT))
        elif len(line) > LINE_LIMIT:
            last = next((l for l in reversed(literals) if l[0] < end and l[1] > start), None)
            prose = last is not None and last[2]
            words = text[max(last[0], start):min(last[1], end)].strip("/*#\"' ") if prose else ""
            unbreakable = last is not None and last[0] < start + LINE_LIMIT and (
                len(words.split()) == 1 if prose
                else re.fullmatch(r"[\s)\]};,{:]*", text[last[1]:end]) is not None)
            if not unbreakable and (prose or not within_limit(line)):
                # A whole-line comment rewraps.
                fix = REWRAP if prose and line.lstrip().startswith("//") else None
                report.add(path, number, "line-length",
                           "line is %d columns, past %d" % (len(line), LINE_LIMIT), fix)
        start = end + 1


def binary_extensions():
    """Returns the extensions that .gitattributes marks binary, as `*.png binary` does, each with its dot."""
    extensions = set()
    path = os.path.join(ROOT, ".gitattributes")
    if os.path.exists(path):
        with open(path, encoding="utf-8") as f:
            for line in f:
                parts = line.split()
                if len(parts) == 2 and parts[1] == "binary" and parts[0].startswith("*."):
                    extensions.add(parts[0][1:])
    return extensions


def check_whitespace(report, path, data):
    """A text file's lines end with LF alone, never with a space or a tab, and its last line ends too. `data` is the
    file's bytes, as a text read would hide a CR. A diff's context lines may end with a space, so a patch may too."""
    if not data or b"\0" in data:
        return
    trailing = not path.endswith(".patch")
    for number, line in enumerate(data.split(b"\n"), 1):
        if line.endswith(b"\r"):
            report.add(path, number, "whitespace", "line ends with CRLF, not LF")
        elif trailing and line.endswith((b" ", b"\t")):
            report.add(path, number, "whitespace", "line ends with whitespace")
    if not data.endswith(b"\n"):
        report.add(path, data.count(b"\n") + 1, "whitespace", "file does not end with a newline")


def comment_run_column(run):
    """Returns the column at which the comments beside a run of code lines, given as (number, end of code, column),
    start. It is the column that most of them use, or the leftmost of tied columns. If a line's code reaches that
    column, it moves right to one space past the end of the longest line's code."""
    counts = {}
    for _, _, at in run:
        counts[at] = counts.get(at, 0) + 1
    shared = min(counts, key=lambda at: (-counts[at], at))
    return max(shared, max(end for _, end, _ in run) + 1)


def check_comment_columns(report, path, text):
    """A comment beside code continues at its own column on the following lines. A comment-only line that follows such
    a comment, indented past the code, starts where that comment starts. Comments beside consecutive lines of code at
    one indentation start at one column (comment_run_column)."""
    column = None       # the column of the comment beside code that the line may continue
    indent = 0          # that code's indentation
    run = []            # the lines of code with comments beside them: (number, end of code, column)

    def check_run():
        shared = comment_run_column(run)
        for number, _, at in run:
            if at != shared:
                report.add(path, number, "comment-align",
                           "comment beside code starts at column %d, not %d" % (at + 1, shared + 1), REWRAP)

    for number, line in enumerate(mask_raw_strings(text).split("\n"), 1):
        stripped = line.lstrip()
        own = len(line) - len(stripped)
        if stripped.startswith("//"):
            if column is not None and own > indent and own != column:
                report.add(path, number, "comment-column",
                           "comment continues at column %d, not %d" % (own + 1, column + 1))
            if column is None or own <= indent:
                column = None
                if run:
                    check_run()
                run = []
            continue
        code = re.sub(r'"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'', lambda m: " " * len(m.group(0)),
                      line)
        at = code.find("//")
        if at > own and (not run or own == indent):
            run.append((number, len(code[:at].rstrip()), at))
        else:
            if run:
                check_run()
            run = [(number, len(code[:at].rstrip()), at)] if at > own else []
        column, indent = (at, own) if at > own else (None, 0)
    if run:
        check_run()


