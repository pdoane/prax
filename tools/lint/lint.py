def posix(path):
    """Returns `path` with forward slashes, which the rules match paths with, whatever the platform separates them
    with."""
    return path.replace(os.sep, "/")

GENERATED = "Generated by "

# Matches a function declaration or definition at namespace scope, capturing its name. It is deliberately narrow: it
# skips anything indented, so members, locals and initializers are ignored.
SIGNATURE = re.compile(
    r"^(?!\s)(?:static\s+|inline\s+|extern\s+|constexpr\s+)*"       # leading keywords
    r"(?:[\w:<>,*&\[\] ]+?[\s*&]+)"                                  # return type
    r"(\w+)\s*\([^;{]*\)\s*(?:const\s*)?(;|\{)",                     # name, args, and which
    re.M)


# The commands that fix the problems that a check finds, if a tool can fix them. The report names each with the files.
REWRAP = "./dev.sh rewrap"
LAYOUT = "./dev.sh layout"
SUITE_FIX = "./dev.sh prax fix"


class Report:
    def __init__(self):
        self.problems = []
        self.fixes = {}     # by problem: the command that fixes it, for each problem that a tool can fix

    def add(self, path, line, rule, message, fix=None):
        """Records a problem. `fix` is the command that fixes it, given the problem's file, if a tool can fix it."""
        problem = (posix(os.path.relpath(path, ROOT)), line, rule, message)
        self.problems.append(problem)
        if fix:
            self.fixes[problem] = fix

    def print(self):
        for path, line, rule, message in sorted(self.problems):
            print("%s:%d: [%s] %s" % (path, line, rule, message))
        print("\n%d problems" % len(self.problems))
        commands = {}
        for (path, _, rule, _), fix in self.fixes.items():
            rules, paths = commands.setdefault(fix, (set(), set()))
            rules.add(rule)
            paths.add(path)
        for fix, (rules, paths) in sorted(commands.items()):
            # The suite's fix rewrites every page, so it takes no file arguments.
            files = "" if fix == SUITE_FIX else " " + " ".join(sorted(paths))
            print("fix %s with: %s%s" % (", ".join(sorted(rules)), fix, files))
        return 1 if self.problems else 0


def line_of(text, index):
    return text.count("\n", 0, index) + 1


def is_generated(text):
    return GENERATED in text[:400]


