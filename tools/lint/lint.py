def tag_module(path):
    """Returns the module that owns the names of a public header: its own, or its interface's for a backend."""
    module = os.path.relpath(public_module(path), ROOT).replace(os.sep, "/")
    return re.split(r"/(?:backends|comparisons)/", module)[0]


def module_tags(module):
    """Returns the tags that `module` owns. A QuickJS layer owns its module's tags after Js."""
    if module in TAGS:
        return TAGS[module]
    if module.endswith("/quickjs"):
        return tuple("Js" + tag for tag in module_tags(os.path.dirname(module)))
    return ("".join(word.capitalize() for word in module.split("/")[-1].split("_")),)


def macro_spelling(tag):
    """Returns `tag` as a macro spells it: ByteView as BYTE_VIEW."""
    return re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", tag).upper()


# Patterns for the names that a public header declares: typedefs, function pointer typedefs, the tags of structures and
# enumerations, enumerations' members, functions, constants and macros.
DECLARED_NAME = (re.compile(r"\btypedef\b[^;(]*?\b(\w+)\s*;"),
                 re.compile(r"\btypedef\b[^;]*?\(\s*\*\s*(\w+)\s*\)"),
                 re.compile(r"\b(?:struct|union|enum)\s+(\w+)\s*[{:]"),
                 re.compile(r"^(?!typedef\b|return\b|#)[A-Za-z_][\w \t*]*?[\s*](\w+)\s*\(", re.M),
                 re.compile(r"^(?:static\s+const|PR_CONSTANT)\b[^=;(]*?\b(\w+)\s*=", re.M),
                 re.compile(r"^\s*#\s*define\s+(\w+)", re.M))
ENUM_BODY = re.compile(r"\benum\b[^{;]*\{([^}]*)\}")


def declared_public_names(code):
    """Returns the prefixed names that the masked code of a public header declares, each with its offset."""
    found = []
    for pattern in DECLARED_NAME:
        found += [(m.group(1), m.start(1)) for m in pattern.finditer(code)]
    for body in ENUM_BODY.finditer(code):
        found += [(m.group(1), body.start(1) + m.start(1))
                  for m in re.finditer(r"(?:^|,)\s*(\w+)", body.group(1))]
    return [(name, at) for name, at in found if re.match(r"(?:Pr|pr|kPr)[A-Z]|PR_[A-Z]", name)]


def check_tags(report, paths, texts):
    """Every public name begins with a tag that its module owns, as a whole word, and each tag has one owner, so that a
    name leads to its module. A name is read by the longest tag that it begins with, so that a module cannot declare
    names under a tag that another module's tag begins with, as lib/font cannot declare PrFontBundle names. Core's
    macros, the annotations of every header, are PR_ alone."""
    owners = {}
    for path in paths:
        module = tag_module(path)
        for tag in module_tags(module):
            if owners.setdefault(tag, module) != module:
                report.add(path, 1, "tag", "%s and %s both own the tag %s" % (owners[tag], module, tag))
    tags = sorted(owners, key=len, reverse=True)
    for path in paths:
        module = tag_module(path)
        text = texts[path]
        for name, at in sorted(set(declared_public_names(mask_non_code(text)))):
            macro = name.startswith("PR_")
            if macro and module == "lib/core":
                continue
            rest = name[3:] if macro else re.sub(r"^(?:kPr|Pr|pr)", "", name)
            tag = next((t for t in tags
                        if re.match(r"%s(?![%s])" % (re.escape(macro_spelling(t) if macro else t),
                                                     "A-Z" if macro else "a-z"), rest)), None)
            if tag is None:
                report.add(path, line_of(text, at), "tag", "%s begins with no module's tag; %s owns %s"
                           % (name, module, ", ".join(module_tags(module))))
            elif owners[tag] != module:
                report.add(path, line_of(text, at), "tag",
                           "%s has the tag %s, which %s owns" % (name, tag, owners[tag]))


