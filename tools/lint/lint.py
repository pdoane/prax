# The words that end the name of a source that implements its header for one platform.
PLATFORM_WORDS = ("posix", "windows", "apple")


def check_homes(report, headers, sources, texts):
    """A header's functions are defined in the source with the same basename, in its module, so a reader finds a
    definition by its header's name."""
    homes = {}
    for path in sources:
        module = header_home(path)[0]
        base = os.path.splitext(os.path.basename(path))[0]
        # A generated source pairs with the hand-written header whose name its name extends, as unicode_data pairs
        # with unicode.
        bases = [base] + (["_".join(base.split("_")[:i]) for i in range(1, base.count("_") + 1)]
                          if is_generated(texts[path]) else [])
        # A header that each platform implements in a source of its own pairs with each of them, as
        # net_sockets_platform_posix pairs with net_sockets_platform.
        platform = re.match(r"(\w+)_(?:%s)$" % "|".join(PLATFORM_WORDS), base)
        if platform is not None:
            bases.append(platform.group(1))
        for name in definitions(texts[path]):
            homes.setdefault(name, set()).update((module, b) for b in bases)
    for path in headers:
        home = header_home(path)
        text = texts[path]
        for match in SIGNATURE.finditer(text):
            name = match.group(1)
            if match.group(2) == ";" and name in homes and home not in homes[name]:
                report.add(path, line_of(text, match.start()), "home",
                           "%s is defined in %s, not %s"
                           % (name, sorted(homes[name])[0][1], home[1]))


