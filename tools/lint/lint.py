# The C++ layers of a library, lib/<module>/<layer>, whose public headers are C++: core's toolkit, and the toolkits that
# the QuickJS layers are written with.
CPP_LAYERS = ("cpp", "quickjs_cpp")


def is_cpp_layer(path):
    """Returns true for a public header of a library's C++ layer, such as lib/core/cpp's or lib/core/quickjs_cpp's:
    public, and C++, so the C++ rules apply to it as to an implementation's headers."""
    return any("/%s/include/" % layer in posix(path) for layer in CPP_LAYERS)


