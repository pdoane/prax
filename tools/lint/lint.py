FORMAT_WORDS = {
    "lib/font": ("sfnt", "cff", "colr", "glyf", "woff"),
    "lib/image": ("png", "gif", "jpeg", "ico", "tiff"),
    "lib/compress": ("inflate", "deflate", "brotli"),
}


def module_words(path):
    """Returns the words that begin the names an internal header of `path` declares: its module's tags, the format
    words that the module owns, `js` in a binding, and a backend's own name."""
    relative = os.path.relpath(path, ROOT).replace(os.sep, "/")
    module = re.split(r"/(?:backends|comparisons|src|tests|quickjs|quickjs_cpp|cpp)/", relative)[0]
    words = [tag.lower() for tag in module_tags(module)] + list(FORMAT_WORDS.get(module, ()))
    backend = re.search(r"/(?:backends|comparisons)/(\w+)/", relative)
    if backend is not None:
        words.append(backend.group(1).replace("_", ""))
    if "/quickjs/" in relative or "/quickjs_cpp/" in relative:
        words.append("js")
    return words


def begins_with_word(name, words):
    """Returns true if `name` begins with one of `words`, ignoring case, as a whole word."""
    return any(name[:len(w)].lower() == w and (len(name) == len(w) or not name[len(w)].islower()) for w in words)


def check_module_words(report, path, text):
    """Every module's implementation shares pr_impl, so a function or a type that an internal header declares at
    namespace scope begins with a word of its module (module_words), as layoutBlock and CssValue do, and two modules
    cannot declare the same name. A source's own names live in its anonymous namespace and need none."""
    words = module_words(path)
    code = mask_non_code(text)
    found = [(m.group(1), m.start(1)) for m in SIGNATURE.finditer(code)
             if m.group(1)[0].islower() and not m.group(1).startswith(("pr", "operator"))
             and m.group(1) not in ("void", "bool", "static_assert", "sizeof", "decltype", "alignof")]
    found += [(m.group(1), m.start(1)) for m in
              re.finditer(r"^(?:struct|enum class|enum|union|using)\s+([A-Z]\w*)\b(?!\s*;)", code, re.M)]
    for name, at in found:
        if not name.startswith("Pr") and not begins_with_word(name, words):
            report.add(path, line_of(text, at), "module-word",
                       "%s begins with none of its module's words: %s" % (name, ", ".join(words)))


def check_header_names(report, paths, texts):
    """A public header is named for the tag of the names that it declares: pr/<tag>.h for a module's main header, and
    pr/<tag>_<topic>.h for the others. The names of a backend's headers start with its directories,
    <interface>_<backend>. A QuickJS layer's header is named for its module's tag, as <tag>_quickjs.h or
    <tag>_<topic>_quickjs.h, and declares names of the layer's tag, Js<tag>."""
    for path in paths:
        stem = os.path.basename(path)[:-2]
        module = os.path.relpath(public_module(path), ROOT).replace(os.sep, "/")
        backend = backend_of(path)
        if backend is not None and not (stem + "_").startswith(backend_file_prefix(backend) + "_"):
            report.add(path, 1, "header-name", "a header of %s is named %s_..." % (backend,
                                                                                  backend_file_prefix(backend)))
        if module in VOCABULARY:
            continue
        tag = stem.split("_")[0]
        if module.endswith("/quickjs"):
            tag = "Js" + tag
        if not re.search(r"\b[Pp]r%s" % tag, texts[path], re.I):
            report.add(path, 1, "header-name", "%s declares no Pr%s names, the tag its name starts with"
                       % (os.path.basename(path), tag.capitalize()))


def file_module(path):
    """Returns the module that a file belongs to, and the kind of directory that it is in: include, src or tests."""
    parts = os.path.relpath(path, ROOT).replace(os.sep, "/").split("/")
    for index, part in enumerate(parts):
        if part in ("include", "src", "tests"):
            return "/".join(parts[:index]), part
    return os.path.dirname(path), ""


def check_unique_names(report, paths):
    """A basename names a file of one module. Within a module, a public header, an internal header and a source may
    share a basename, as a source shares the name of its headers."""
    seen = {}
    for path in paths:
        module, kind = file_module(path)
        stem, extension = os.path.splitext(os.path.basename(path))
        role = "public" if kind == "include" else "header" if extension == ".h" else "source"
        for other, other_module, other_role in seen.get(stem, []):
            if other_module != module or other_role == role:
                report.add(path, 1, "unique-name", "%s shares its name with %s"
                           % (os.path.basename(path), posix(os.path.relpath(other, ROOT))))
                break
        seen.setdefault(stem, []).append((path, module, role))


def parameter_names(signature):
    """Returns the names of a function signature's parameters, in order, with None for a parameter without a name."""
    start = signature.index("(")
    depth = 0
    for end in range(start, len(signature)):
        depth += {"(": 1, ")": -1}.get(signature[end], 0)
        if depth == 0:
            break
    args = re.sub(r"//[^\n]*|/\*.*?\*/", "", signature[start + 1:end], flags=re.S)
    parts, depth, current = [], 0, ""
    for char in args:
        depth += {"(": 1, "<": 1, "[": 1, ")": -1, ">": -1, "]": -1}.get(char, 0)
        if char == "," and depth == 0:
            parts.append(current)
            current = ""
        else:
            current += char
    parts.append(current)
    names = []
    for part in parts:
        part = part.split("=")[0].strip()
        if not part or part == "void" or part == "...":
            continue
        pointer = re.search(r"\(\s*[*&]\s*(?:PR_\w+\s+)?(\w+)\s*\)", part)
        if pointer:
            names.append(pointer.group(1))
            continue
        part = re.sub(r"\[[^\]]*\]", "", part).strip()
        # A type ending in a pointer or reference, or a qualified type alone, has no name.
        if part.endswith(("*", "&")) or re.fullmatch(r"const\s+[\w:]+", part):
            names.append(None)
            continue
        words = re.findall(r"\w+", part)
        # A lone type, or a type ending in a nullability or other macro, has no name.
        names.append(words[-1] if len(words) > 1 and not re.fullmatch(r"PR_[A-Z_]+|const|unsigned|signed|long|short|"
                                                                      r"int|char|float|double|bool", words[-1])
                     else None)
    return names


def check_parameter_names(report, header_path, header_text, source_path, source_text):
    """A function's definition names its parameters as its declaration does, if the name declares and defines one
    function."""
    declared = {}
    for match in SIGNATURE.finditer(header_text):
        if match.group(2) == ";":
            declared.setdefault(match.group(1), []).append(match.group(0))
    defined = {}
    for match in SIGNATURE.finditer(source_text):
        if match.group(2) == "{":
            defined.setdefault(match.group(1), []).append((match.group(0), line_of(source_text, match.start())))
    for name, signatures in defined.items():
        if len(signatures) != 1 or len(declared.get(name, [])) != 1:
            continue
        here, line = signatures[0]
        there = parameter_names(declared[name][0])
        names = parameter_names(here)
        if len(there) != len(names):
            continue
        for index, (a, b) in enumerate(zip(names, there)):
            if a and b and a != b:
                report.add(source_path, line, "parameter-names",
                           "parameter %d of %s is `%s`, and `%s` in %s" % (index + 1, name, a, b,
                                                                         os.path.basename(header_path)))


def check_correspondence(report, header_path, header_text, source_path, source_text):
    """A declaration and its implementation correspond: same basename, same order."""
    declared = declarations(header_text)
    defined = definitions(source_text)
    if not declared or not defined:
        return

    # Only the declarations that this source actually implements take part, so a header split across several sources
    # still lines up.
    implemented = [name for name in declared if name in defined]
    ordered = [name for name in defined if name in implemented]
    if implemented != ordered:
        report.add(source_path, 1, "correspondence",
                   "definitions are ordered %s but %s declares %s"
                   % (", ".join(ordered[:6]), os.path.basename(header_path),
                      ", ".join(implemented[:6])))


