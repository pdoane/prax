# the draw comparison and the viewer share.
CPP_API_DIRECTORIES = ("lib/draw/comparisons/imgui/config/",)


def is_cpp_api(path):
    """Returns true for a header of the C++ API, namespace pr, which applications use: a language layer's public
    header, or a header of a directory in CPP_API_DIRECTORIES."""
    relative = os.path.relpath(path, ROOT).replace(os.sep, "/")
    return path.endswith(".h") and (is_cpp_layer(path) or relative.startswith(CPP_API_DIRECTORIES))


def is_public(path):
    """Returns true for a public C header: the C++ rules do not apply to it, and the public API's do."""
    return "/include/" in posix(path) and not is_cpp_layer(path)


# The modules that every target may use without linking them by name: core, and its C++ layer, which every
# implementation is written with.
FOUNDATION = ("core", "core_cpp")


def check_module_dependencies(report):
    """A target links each module whose public headers its files include, so the build's CMake states every dependency
    and a new one shows in its link lines. A public header includes only what the target links publicly, because its
    clients include it too. A target links no module that it includes nothing of, unless the module is a program's
    implementation, such as a backend that it calls through an interface. Every engine target that a target links is
    declared, on every platform, because CMake reports a missing one only when it configures the branch that links
    it."""
    graph = modules.targets(ROOT)
    owners = modules.header_owners(ROOT, graph)
    implementations = modules.source_owners(graph)
    for target in sorted(graph.values(), key=lambda target: target.name):
        if target.kind is None:
            continue
        used = set()
        for path in sorted(modules.files(ROOT, target)):
            public = "/include/pr/" in path.replace(os.sep, "/")
            with open(path, encoding="utf-8") as f:
                text = f.read()
            # An internal header uses its module as a public header does, and the modules whose headers it includes,
            # which its includer needs on its include path.
            for match in re.finditer(r'^#include "(([\w/]+)/[^/"]+\.h)"', text, re.M):
                if match.group(2) not in implementations:
                    continue
                used.add(implementations[match.group(2)])
                internal = os.path.join(ROOT, "lib", match.group(1))
                if os.path.exists(internal):
                    with open(internal, encoding="utf-8") as header:
                        for name in re.findall(r'^#include "pr/([^"]+)"', header.read(), re.M):
                            if owners.get(name) is not None:
                                used.add(owners[name])
            for match in re.finditer(r'^#include "pr/([^"]+)"', text, re.M):
                owner = owners.get(match.group(1))
                if owner is None or owner == target.name:
                    continue
                used.add(owner)
                visibility = target.links.get(owner)
                if visibility is None and owner not in FOUNDATION:
                    report.add(path, line_of(text, match.start()), "module-dependency",
                               "%s includes pr/%s, of %s, which it does not link" %
                               (target.name, match.group(1), owner))
                elif public and visibility == "PRIVATE":
                    report.add(path, line_of(text, match.start()), "module-dependency",
                               "a public header of %s includes pr/%s, of %s, which it links privately" %
                               (target.name, match.group(1), owner))
        for linked, (cmake, line) in sorted(target.link_lines.items()):
            declared = graph.get(linked)
            undeclared = declared is None or (declared.kind is None and declared.alias is None)
            if linked in target.engine_links and undeclared:
                report.add(os.path.join(ROOT, cmake), line, "module-dependency",
                           "%s links prax::%s, which no target is" % (target.name, linked))
            elif linked in owners.values() and linked not in used and linked not in FOUNDATION:
                report.add(os.path.join(ROOT, cmake), line, "module-dependency",
                           "%s links %s, but includes none of its headers" % (target.name, linked))


