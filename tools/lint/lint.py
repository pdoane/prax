def check_test_cases(report, path, text):
    """A test case is at global scope, after the pr_impl block that holds the file's helpers, so that no test case
    sits in the anonymous namespace or in pr_impl."""
    code = mask_non_code(text)
    braces = list(re.finditer(r"\{|\}", code))
    for match in re.finditer(r"^[ \t]*TEST_CASE\b", code, re.M):
        depth = 0
        for brace in braces:
            if brace.start() >= match.start():
                break
            depth += 1 if brace.group(0) == "{" else -1
        if depth != 0:
            report.add(path, line_of(text, match.start()), "test-case",
                       "TEST_CASE inside a namespace or block; test cases go at global scope after pr_impl")


def check_global_definitions(report, path, text):
    """A source's functions are file-local, in its anonymous namespace; internal, in pr_impl; or the public C API that
    it implements, at global scope. Anything else at global scope would reach the linker with no prefix or
    namespace."""
    code = mask_non_code(text)
    braces = list(re.finditer(r"\{|\}", code))
    for match in SIGNATURE.finditer(code):
        name = match.group(1)
        if match.group(2) != "{" or name.startswith(("pr", "js")) or name == "main":
            continue
        depth = 0
        for brace in braces:
            if brace.start() >= match.start():
                break
            depth += 1 if brace.group(0) == "{" else -1
        if depth != 0:
            continue
        report.add(path, line_of(text, match.start()), "global",
                   "%s is defined at global scope; it belongs in pr_impl or the anonymous "
                   "namespace" % name)


def check_namespace_layout(report, path, text, name):
    """A source has one block of its namespace, `name`, that holds everything but the C API, with its anonymous
    namespace nested inside it. After the block come a using-directive and the public C definitions. The directive is
    present exactly when definitions follow, so that they read without a qualifier."""
    lines = text.split("\n")
    spans = namespace_spans(mask_non_code(text), name)
    opens = [line_of(text, a) for a, _ in spans]
    using = [n for n, line in enumerate(lines, 1) if line.rstrip() == "using namespace %s;" % name]
    for number in opens[1:]:
        report.add(path, number, "namespace-layout", "second %s block" % name)
    first, last = (opens[0], line_of(text, spans[0][1])) if spans else (0, 0)
    if opens:
        tail = [n for n, line in enumerate(lines, 1)
                if n > last and line.strip() and not line.lstrip().startswith(("//", "#"))
                and line.strip() != "PR_ASSUME_NONNULL_END" and n not in using]
        for number in using:
            if number < first:
                report.add(path, number, "namespace-layout",
                           "using-directive above the %s block" % name)
        below = [n for n in using if n > last]
        if tail and not below:
            report.add(path, last, "namespace-layout",
                       "definitions follow the %s block without a using-directive" % name)
        if below and not tail:
            report.add(path, below[0], "namespace-layout",
                       "using-directive with no definitions below the %s block" % name)
    for number, line in enumerate(lines, 1):
        if line.rstrip() == "namespace {" and not first < number < last:
            report.add(path, number, "namespace-layout", "anonymous namespace outside %s" % name)


def check_header_namespace_layout(report, path, text, name):
    """An internal header, or a header of the C++ API, has one block of its namespace, `name`, that holds its
    declarations. After the block come only the C opaque types of the handles that it defines. A type that derives from
    an opaque type is declared in its own header, after the header that declares the base."""
    lines = text.split("\n")
    spans = namespace_spans(mask_non_code(text), name)
    for start, _ in spans[1:]:
        report.add(path, line_of(text, start), "namespace-layout", "second %s block" % name)
    if not spans:
        return
    last = line_of(text, spans[-1][1])
    directive = False   # whether the line continues a preprocessor directive, such as a macro's body
    for number, line in enumerate(lines, 1):
        stripped = line.strip()
        continued = directive
        directive = (continued or stripped.startswith("#")) and stripped.endswith("\\")
        if number <= last or not stripped or stripped.startswith(("//", "#")) or continued:
            continue
        if stripped == "PR_ASSUME_NONNULL_END" or OPAQUE_TYPE.match(stripped):
            continue
        report.add(path, number, "namespace-layout",
                   "only C opaque types follow the pr_impl block")


PUBLIC_NAME = re.compile(r"\b((?:Pr|pr)[A-Z]\w*)")
UPCAST = re.compile(r"PR_HANDLE_UPCAST\(\s*(\w+)\s*,\s*(\w+)\s*,\s*(\w+)\s*\)")


def public_names(texts):
    """Returns the names that the public headers declare, including the upcasts that PR_HANDLE_UPCAST makes."""
    names = set()
    for text in texts:
        names |= set(PUBLIC_NAME.findall(text))
        for derived, base, name in UPCAST.findall(text):
            names.add("pr%sAs%s" % (derived, name))
            names.add("pr%sAsConst%s" % (derived, name))
    return names


def check_internal_names(report, path, text, names):
    """The Pr and pr prefixes belong to the public API. Internal code names its own declarations in pr_impl without
    them. An Objective-C class, which no namespace can hold, keeps the prefix, as does a function with C linkage, which
    reaches the linker by its name alone (check_linkage)."""
    code = mask_non_code(text)
    classes = set(re.findall(r"@(?:interface|implementation)\s+(\w+)", code)) | c_linkage_names(text)
    reported = set()
    for match in PUBLIC_NAME.finditer(code):
        name = match.group(1)
        if name in names or name in classes or name in reported or name in CPP_GLOBAL_NAMES or name.endswith("_"):
            continue
        reported.add(name)
        report.add(path, line_of(text, match.start()), "internal-name",
                   "%s is no public name; internal code drops the prefix" % name)


PUBLIC_TYPE = re.compile(r"\btypedef\s+struct\s+(Pr[A-Z]\w*)|\}\s*(Pr[A-Z]\w*)\s*;|"
                         r"\btypedef\s+[\w\s*]+?\b(Pr[A-Z]\w*)\s*;|\(\s*\*\s*(Pr[A-Z]\w*)\s*\)")
INTERNAL_TYPE = re.compile(r"^\s*(?:(?:struct|class|union)\s+([A-Z]\w*)\b(?!\s*:\s*\w)|"
                           r"(?:struct|class|union)\s+([A-Z]\w*)\s*:|"
                           r"typedef\s+[\w\s:<>*,]+?\b([A-Z]\w*)\s*;|using\s+([A-Z]\w*)\s*=)", re.M)
HANDLE_BASE = re.compile(r"\bstruct\s+Pr(\w+)\s*:\s*(?:pr_impl::)?(\w+)\s*\{")


def public_types(texts):
    """Returns the type names that the public headers declare, without their Pr prefix."""
    names = set()
    for text in texts:
        for match in PUBLIC_TYPE.finditer(text):
            names.add(next(group for group in match.groups() if group)[2:])
    return names


def handle_bases(texts):
    """Returns the internal types that are the base of the handle with their own name: struct PrX : pr_impl::X {}."""
    return {derived for text in texts for derived, base in HANDLE_BASE.findall(text) if derived == base}


def check_shadowed_types(report, path, text, types, bases):
    """PrX and pr_impl::X are one type. The only internal type with a public name is the base of that name's handle,
    declared as struct PrX : pr_impl::X {}. A public enum, structure or typedef has no internal namesake, which would
    make one name mean two things."""
    code = mask_non_code(text)
    for match in INTERNAL_TYPE.finditer(code):
        group = next(index for index, group in enumerate(match.groups(), 1) if group)
        name = match.group(group)
        if name in types and name not in bases:
            report.add(path, line_of(text, match.start(group)), "shadowed-type",
                       "%s is the public Pr%s's name; only Pr%s's handle base may take it" % (name, name, name))


PARALLEL_ENUM = re.compile(r"\b(Pr[A-Z]\w*?)_\w+\)?\s*==\s*(?:\w+\()?((?!Pr|k)[A-Z]\w*?)_\w+|"
                           r"\b((?!Pr|k)[A-Z]\w*?)_\w+\)?\s*==\s*(?:\w+\()?(Pr[A-Z]\w*?)_\w+")


def check_parallel_enums(report, path, text):
    """A public enum is used as it is. An internal enum kept in step with a public one, member for member, is the same
    set under two names. A static_assert that compares their members reveals such an enum."""
    for match in re.finditer(r"static_assert\((.*?)\);", text, re.S):
        found = PARALLEL_ENUM.search(match.group(1))
        if found:
            public = found.group(1) or found.group(4)
            internal = found.group(2) or found.group(3)
            report.add(path, line_of(text, match.start()), "parallel-enum",
                       "%s is kept in step with %s; use %s" % (internal, public, public))


MACRO_CONSTANT = re.compile(r"^#define\s+(PR_[A-Z0-9_]+)\s+\(?\s*-?\s*(?:0x[0-9a-fA-F]+|[0-9])", re.M)


def check_macro_constants(report, path, text):
    """A public header spells an integer constant as `enum { kPrX = n }` and a floating-point constant as
    `PR_CONSTANT float kPrX`, which is constexpr in C++. A macro holds a value only if the preprocessor reads it, in an
    #if."""
    for match in MACRO_CONSTANT.finditer(text):
        name = match.group(1)
        if re.search(r"^#\s*(?:el)?if\b.*\b%s\b" % name, text, re.M):
            continue
        report.add(path, line_of(text, match.start()), "macro-constant",
                   "%s is a macro; a constant is an enum or a PR_CONSTANT" % name)


# The words that an array's `by` comment may use for its index if no type names the domain: positions in the data that
# the array runs beside, which every reader knows.
INDEX_WORDS = ("byte", "code point", "glyph", "slot", "atom", "property", "matcher", "override", "visual position",
               "index", "unit", "kind")

ARRAY_FIELD = re.compile(r"^\s+Array<[^;]*>\s+\w+;\s*//\s*(.*)$", re.M)


def declared_types(texts):
    """Returns every type name that the headers declare: structures, classes, the typedefs of enums and other
    typedefs."""
    names = set()
    for text in texts:
        names.update(re.findall(r"\b(?:struct|class)\s+(\w+)", text))
        names.update(re.findall(r"\btypedef\b[^;]*?\b(\w+)\s*;", text))
    return names


def check_index_domains(report, path, text, types):
    """An array whose index is not simply a position says what indexes it: `// by <domain>`, where the domain is a
    type that names the index (a typedef such as LayoutNodeIndex) or one of a few words that every reader knows
    (INDEX_WORDS). One name for each domain lets a reader match an index to the arrays that it reads."""
    for match in ARRAY_FIELD.finditer(text):
        comment = match.group(1)
        for by in re.finditer(r"^by ([A-Za-z][\w ]*)", comment):
            domain = by.group(1)
            first = domain.split(" ")[0]
            if first[0].isupper():
                if first not in types:
                    report.add(path, line_of(text, match.start()), "index-domain",
                               "`by %s` names no type" % first)
            elif not any(domain == word or domain.startswith(word + " ") for word in INDEX_WORDS):
                report.add(path, line_of(text, match.start()), "index-domain",
                           "`by %s` names no index domain: a type, or one of %s" % (domain, ", ".join(INDEX_WORDS)))


def c_linkage_names(text):
    """Returns the names that a file declares with C linkage, one declaration at a time."""
    return set(re.findall(r'^\s*extern "C" [^;{(]*?\b(\w+)\s*\(', text, re.M))


# The functions of the C library that core's C++ layer declares for MSVC, which has no builtins for them.
C_LIBRARY = {"acos", "acosf", "asin", "atan", "atan2", "atan2f", "atanf", "cbrt", "ceil", "ceilf", "cos", "cosf",
             "exp", "expf", "fabs", "floor", "floorf", "fmod", "fmodf", "hypot", "log", "log2f", "logf", "memchr",
             "memcpy", "memmove", "memset", "pow", "powf", "round", "roundf", "sin", "sinf", "sqrt", "sqrtf", "tan",
             "tanf"}


def check_linkage(report, path, text):
    """Only the public headers give C linkage. A definition takes it from the declaration that it implements, so
    internal code opens no extern "C" block and defines nothing with it. Internal code declares with C linkage only
    what C defines: a compiler intrinsic, whose name starts with an underscore, a function of the C library that
    C_LIBRARY names, a tree-sitter grammar's function (tree_sitter_<grammar>), which its generated parser defines, or a
    test's C translation unit, whose functions take the library's prefix because they reach the linker by their names
    alone. Such a declaration is at global scope, where the name it declares lives."""
    code = mask_non_code(text)
    for match in re.finditer(r'^([ \t]*)extern "C" [^;{(]*?\b(\w+)\s*\(', text, re.M):
        if code[match.start(2)] == " ":
            continue
        name = match.group(2)
        if not name.startswith(("pr", "_", "tree_sitter_")) and name not in C_LIBRARY:
            report.add(path, line_of(text, match.start()), "linkage",
                       'extern "C" %s has no prefix; a name with C linkage takes pr' % name)
        spans = namespace_spans(code, r"\w+") + namespace_spans(code.replace("namespace {", "namespace _ {"), "_")
        if match.group(1) or any(a <= match.start() < b for a, b in spans):
            report.add(path, line_of(text, match.start()), "linkage",
                       'extern "C" %s is declared in a namespace; declare it at global scope' % name)
    for match in re.finditer(r'\bextern\s+"C"\s*([^;{]*)([;{])', text):
        if code[match.start()] == " ":
            continue
        if match.group(2) == "{":
            what = "block" if not match.group(1).strip() else "definition"
            report.add(path, line_of(text, match.start()), "linkage",
                       'extern "C" %s outside a public header' % what)


def check_example_includes(report, path, text):
    """examples/ and apps/ hold applications, which a library and its tests never depend on."""
    for match in re.finditer(r'#include [<"]((?:examples|apps)/[^">]+)[">]', text):
        report.add(path, line_of(text, match.start()), "example-include",
                   "a library includes %s" % match.group(1))


def check_application_includes(report, path, text):
    """An application under examples/ or apps/ depends on no other application: what two of them share belongs in a
    library."""
    relative = os.path.relpath(path, ROOT).replace(os.sep, "/")
    if not relative.startswith(("examples/", "apps/")):
        return
    own = "/".join(relative.split("/")[:2]) + "/"
    for match in re.finditer(r'#include [<"]((?:examples|apps)/[^/">]+/[^">]+)[">]', text):
        if not match.group(1).startswith(own):
            report.add(path, line_of(text, match.start()), "application-include",
                       "an application includes %s, of another application" % match.group(1))


def check_constant_names(report, path, text):
    """Constants take the k prefix, including inside the anonymous namespace. k marks a constant, and pr/Pr/PR_ marks
    the library. In C++ a constant is `constexpr`, so that no work runs before main. A unit test may do that work, and
    its constants may be `const`. A public C header spells one as `enum { kX = n }`."""
    public = is_public(path)
    for match in re.finditer(
            r"^(?:static\s+)?(const|constexpr)\s+([\w:<>*]+)\s+(\w+)\s*(?:\[[^\]]*\])?\s*=",
            text, re.M):
        # A pointer to const is a variable, because the const applies to what it points to.
        if match.group(1) == "const" and match.group(2).endswith("*"):
            continue
        name = match.group(3)
        if not re.match(r"^k[A-Z]", name):
            report.add(path, line_of(text, match.start()), "constant-name",
                       "file-scope constant %s is not spelled kSomething" % name)
        elif match.group(1) == "const" and not public and not is_test(path):
            report.add(path, line_of(text, match.start()), "constant-form",
                       "%s is const; a C++ constant is constexpr" % name)
    for match in re.finditer(r"^enum(?: : \w+)? \{\s*(k[A-Z]\w*)", text, re.M):
        if not public:
            report.add(path, line_of(text, match.start()), "constant-form",
                       "%s is an enum; a C++ constant is constexpr" % match.group(1))


def check_padding_names(report, path, text):
    """Filler bytes are named _pad. A field of another type may be named pad for what it is, such as CSS padding."""
    for match in re.finditer(r"^\s+(?:u?int(?:8|16|32|64)_t|char)\s+(pad\w*)\s*(\[|;)", text, re.M):
        report.add(path, line_of(text, match.start()), "padding-name",
                   "padding field %s should be _pad" % match.group(1))


# A parameter named self: a type or a qualifier stands before the name, and the end of the parameter after it. An
# argument that passes Objective-C's self has no type before it.
SELF_PARAMETER = re.compile(r"[(,]\s*[^(),;{}]*\w[\s*&]+(?:self|thisValue)\s*(?=[,)=])")

# A local pointer named self, which stands for the object that a method's receiver would be.
SELF_POINTER = re.compile(r"^[ \t]*(?:const\s+)?\w+\*\s*self\s*=", re.M)


def check_self_parameter(report, path, text):
    """The API is functions over data, not objects with methods, so a parameter, or a local that a callback's context
    becomes, is named for what it is. Objective-C's own self is left alone, and so is a flag or a value for which self
    is the domain's word, as in CSS's align-self."""
    code = mask_non_code(text)
    for match in SELF_PARAMETER.finditer(code):
        report.add(path, line_of(text, match.end()), "self-parameter",
                   "a parameter named for a method's receiver; name it for what it is, as this is not an object-oriented API")
    for match in SELF_POINTER.finditer(code):
        report.add(path, line_of(text, match.end()), "self-parameter",
                   "a pointer named self; name it for what it is, as this is not an object-oriented API")


def check_anonymous_namespace(report, path, text):
    """File-local code goes in one anonymous namespace per file, not behind `static`. Nothing in it reaches the linker,
    so nothing in it needs a prefix either."""
    for match in re.finditer(r"^static\s+(?!const\b|constexpr\b|inline\b)[\w:<>*&]+\s+\w+\s*\(",
                             text, re.M):
        report.add(path, line_of(text, match.start()), "anonymous-namespace",
                   "file-local function uses static; use the anonymous namespace")

    opens = len(re.findall(r"^namespace \{", text, re.M))
    if opens > 1:
        report.add(path, 1, "anonymous-namespace",
                   "%d anonymous namespaces; one per file" % opens)


