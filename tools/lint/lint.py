# Spec references

WEBREF = os.path.join(ROOT, "third_party", "webref", "ed")

SHORTNAME = r"\b([a-z][a-z0-9]*(?:-[a-z0-9]+)*)"

# Matches a spec reference such as `css-syntax-3/#consume-escaped-code-point`: a spec's shortname and the id of the
# passage. An id may hold balanced parentheses, as in `attribute-value-(double-quoted)-state`, and does not end in the
# punctuation of the surrounding sentence. A shortname inside a URL is not a reference. A shortname may hold capitals,
# as SVG2 and DOM-Parsing do.
SPEC_ID = re.compile(r"(?<![\w./:-])([A-Za-z][A-Za-z0-9]*(?:-[A-Za-z0-9]+)*)" +
                     r"/#((?:[A-Za-z0-9_%]|[.:\-](?=[A-Za-z0-9_%(\-])|'(?=[A-Za-z]+-)|\([A-Za-z0-9_.:%\-]*\))+)")

# Matches a shortname followed by a section number or a quoted name, which a reference does not use, on one line or
# across a comment's line break.
SPEC_OTHER = re.compile(SHORTNAME + r'(?: |\n\s*(?://|#|\*) *)'
                        r'(?:\d+(?:\.\d+)*\b|[A-Z](?:\.\d+)*\b|\\?")')

# The source files a reference can be in, by extension.
SPEC_FILES = (".h", ".hpp", ".c", ".cpp", ".py", ".md", ".js", ".txt")


def spec_ids():
    """Returns the ids of every passage of each spec that webref extracts (its headings, its definitions, and the steps
    and other elements that carry an id), by shortname."""
    extracts = os.path.join(WEBREF, "ids")
    if not os.path.isdir(extracts):
        sys.exit("no webref ids at %s; run ./dev.sh fetch webref" % extracts)
    ids = {}
    for file in os.listdir(extracts):
        with open(os.path.join(extracts, file), encoding="utf-8") as f:
            urls = json.load(f)["ids"]
        ids[file[:-len(".json")]] = {urllib.parse.unquote(url[url.index("#") + 1:])
                                     for url in urls if "#" in url}
    ids.update(markdown_spec_ids())
    return ids


