def set_shared(value, root):
    """Sets the state that the checks share, and the root they check under, in a worker that did not fork from the
    process that computed them."""
    global shared, ROOT
    shared = value
    ROOT = root


def check_each(report, check, paths):
    """Runs `check` on each of `paths`, across the machine's cores, and adds what it finds to `report`. A worker forks
    with the shared state and the root where the system forks, and is handed a copy of them where it does not, as on
    Windows."""
    if "fork" in multiprocessing.get_all_start_methods():
        pool = multiprocessing.get_context("fork").Pool()
    else:
        pool = multiprocessing.get_context("spawn").Pool(initializer=set_shared, initargs=(shared, ROOT))
    with pool:
        for problems, fixes in pool.map(check, paths, chunksize=8):
            report.problems.extend(problems)
            report.fixes.update(fixes)


